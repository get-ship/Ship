import { existsSync, readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

import { describe, expect, it } from 'bun:test'

import suiPlugin from '../src/index'

const here = dirname(fileURLToPath(import.meta.url))
const fixturesDir = join(here, 'fixtures')
const repoRoot = resolve(here, '..', '..', '..')
const compilerPath = join(repoRoot, 'target', 'release', 'sui-compiler')
const compilerExists = existsSync(compilerPath)

const skipIfNoCompiler = compilerExists ? it : it.skip

interface ViteTransformResult {
  code: string
  map: { version: 3; sources: string[] }
}

async function callTransform(file: string): Promise<ViteTransformResult> {
  const plugin = suiPlugin({ compilerPath })
  // Plugin contract: name 'vite-plugin-sui'. Sanity check.
  expect(plugin.name).toBe('vite-plugin-sui')
  const transform = plugin.transform as
    | ((src: string, id: string) => Promise<ViteTransformResult | null>)
    | { handler: (src: string, id: string) => Promise<ViteTransformResult | null> }
  const handler = typeof transform === 'function' ? transform : transform.handler
  const src = readFileSync(file, 'utf8')
  // Vite passes plugin handlers through with `this` set to a context object,
  // but our handler doesn't reference `this`, so a direct call is fine.
  const result = await handler(src, file)
  if (!result) throw new Error(`transform returned null for ${file}`)
  return result
}

describe('vite-plugin-sui transform', () => {
  skipIfNoCompiler('returns null for non-.sui ids', async () => {
    const plugin = suiPlugin({ compilerPath })
    const handler = plugin.transform as (src: string, id: string) => Promise<unknown>
    const result = await (typeof handler === 'function'
      ? handler
      : (handler as { handler: typeof handler }).handler)('// js', '/some/file.ts')
    expect(result).toBeNull()
  })

  skipIfNoCompiler('compiles a view fixture and emits the auto-generated header', async () => {
    const result = await callTransform(join(fixturesDir, 'views', 'static-view.sui'))
    expect(result.code).toContain('AUTO-GENERATED by sui-compiler')
    // Static view fixture has no state, so no bindText/on imports.
    expect(result.code).toMatch(/from\s+"@ship\/ui-runtime"/)
    // Stub source map points back at the source file.
    expect(result.map.version).toBe(3)
    expect(result.map.sources).toEqual([join(fixturesDir, 'views', 'static-view.sui')])
  })

  skipIfNoCompiler('compiles a component fixture in component mode', async () => {
    const result = await callTransform(join(fixturesDir, 'sui-fixture', 'sui-fixture.sui'))
    expect(result.code).toContain('AUTO-GENERATED by sui-compiler')
    // Component output is wrapped by `component("<tag>", { ... })` from
    // @ship/ui-runtime; that wrapper is what registers the custom element
    // at module-eval time. The compiler-side signal we care about here is
    // that the tag name landed correctly.
    expect(result.code).toMatch(/component\(\s*"sui-fixture"/)
    expect(result.code).toMatch(/from\s+"@ship\/ui-runtime"/)
  })

  skipIfNoCompiler('emits matching JS for two consecutive transforms (no temp-dir leak)', async () => {
    const file = join(fixturesDir, 'views', 'static-view.sui')
    const a = await callTransform(file)
    const b = await callTransform(file)
    expect(a.code).toBe(b.code)
  })

  it('throws a clear error when compilerPath does not exist', async () => {
    const plugin = suiPlugin({ compilerPath: '/no/such/compiler' })
    const handler = plugin.transform as
      | ((src: string, id: string) => Promise<unknown>)
      | { handler: (src: string, id: string) => Promise<unknown> }
    const fn = typeof handler === 'function' ? handler : handler.handler
    await expect(fn('', join(fixturesDir, 'views', 'static-view.sui'))).rejects.toThrow(
      /compilerPath does not exist/,
    )
  })
})
