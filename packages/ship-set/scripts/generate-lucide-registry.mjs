#!/usr/bin/env node
/**
 * Generate the lucide registry in two forms:
 *
 *   1. `src/web-components/core/lucide-icons.generated.ts` — typed
 *      record consumed at build time by Lit `ship-elements` web
 *      components (ship-icon, ship-error-state, ship-empty-state).
 *      These ship in `ship-elements.js`, which still loads the table
 *      synchronously.
 *
 *   2. `crates/ship-sui-server/assets/lucide-icons.json` — the same
 *      table as plain JSON, served to the page on demand at
 *      `/_sui/lucide-icons.json`. The SUI `<sui-icon>` controller
 *      fetches it on first mount instead of bundling the table into
 *      `sui-components.js` (R4 of the components-bundle audit).
 *
 * The curated approach keeps the bundle small — 1947 icons ship in
 * lucide-static; we ship only what views reference.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = dirname(here)
const allowlist = JSON.parse(
  readFileSync(join(here, 'lucide-allowlist.json'), 'utf8')
)
const lucideDir = join(root, 'node_modules', 'lucide-static', 'icons')

function extractInner(svg) {
  // Strip license comment, then extract everything between the opening
  // <svg ...> tag and the closing </svg>.
  const stripped = svg.replace(/<!--[\s\S]*?-->/g, '').trim()
  const open = stripped.indexOf('<svg')
  const openEnd = stripped.indexOf('>', open)
  const closeStart = stripped.lastIndexOf('</svg>')
  if (open < 0 || openEnd < 0 || closeStart < 0) {
    throw new Error('malformed SVG')
  }
  return stripped.slice(openEnd + 1, closeStart).trim().replace(/\s+/g, ' ')
}

const entries = []
for (const name of allowlist.icons) {
  const path = join(lucideDir, `${name}.svg`)
  const raw = readFileSync(path, 'utf8')
  entries.push([name, extractInner(raw)])
}

let out = `// Auto-generated by scripts/generate-lucide-registry.mjs.\n`
out += `// Do not edit by hand. Regenerate via \`bun run --filter @ship/set build\`.\n`
out += `// Source: lucide-static (ISC) — https://lucide.dev\n\n`
out += `export const LUCIDE_ICONS: Record<string, string> = {\n`
for (const [name, inner] of entries) {
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},\n`
}
out += `}\n`

const dest = join(root, 'src', 'web-components', 'core', 'lucide-icons.generated.ts')
writeFileSync(dest, out)
console.log(`wrote ${dest} with ${entries.length} icons`)

// JSON form, served at `/_sui/lucide-icons.json` and `include_str!`'d
// into the daemon. Sorted keys for deterministic output so the
// `cargo build`-time content hash only changes when the icon set
// actually changes.
const jsonDest = join(
  root, '..', '..', 'crates', 'ship-sui-server', 'assets', 'lucide-icons.json',
)
const jsonObj = Object.fromEntries(
  [...entries].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)),
)
writeFileSync(jsonDest, JSON.stringify(jsonObj))
console.log(`wrote ${jsonDest} with ${entries.length} icons`)
