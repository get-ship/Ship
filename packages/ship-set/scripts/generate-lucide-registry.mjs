#!/usr/bin/env node
/**
 * Generate `src/web-components/core/lucide-icons.generated.ts` from
 * the curated icon allowlist (`scripts/lucide-allowlist.json`). For
 * each icon, reads `lucide-static/icons/<name>.svg`, extracts the
 * inner SVG markup (children of the root <svg>), and writes a typed
 * record. The curated approach keeps the bundle small — 1947 icons
 * ship in lucide-static; we ship only what views reference.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = dirname(here)
const allowlist = JSON.parse(
  readFileSync(join(here, 'lucide-allowlist.json'), 'utf8')
)
const lucideDir = join(root, 'node_modules', 'lucide-static', 'icons')

function extractInner(svg) {
  // Strip license comment, then extract everything between the opening
  // <svg ...> tag and the closing </svg>.
  const stripped = svg.replace(/<!--[\s\S]*?-->/g, '').trim()
  const open = stripped.indexOf('<svg')
  const openEnd = stripped.indexOf('>', open)
  const closeStart = stripped.lastIndexOf('</svg>')
  if (open < 0 || openEnd < 0 || closeStart < 0) {
    throw new Error('malformed SVG')
  }
  return stripped.slice(openEnd + 1, closeStart).trim().replace(/\s+/g, ' ')
}

const entries = []
for (const name of allowlist.icons) {
  const path = join(lucideDir, `${name}.svg`)
  const raw = readFileSync(path, 'utf8')
  entries.push([name, extractInner(raw)])
}

let out = `// Auto-generated by scripts/generate-lucide-registry.mjs.\n`
out += `// Do not edit by hand. Regenerate via \`pnpm -F @ship/set build\`.\n`
out += `// Source: lucide-static (ISC) — https://lucide.dev\n\n`
out += `export const LUCIDE_ICONS: Record<string, string> = {\n`
for (const [name, inner] of entries) {
  out += `  ${JSON.stringify(name)}: ${JSON.stringify(inner)},\n`
}
out += `}\n`

const dest = join(root, 'src', 'web-components', 'core', 'lucide-icons.generated.ts')
writeFileSync(dest, out)
console.log(`wrote ${dest} with ${entries.length} icons`)
