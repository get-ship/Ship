// ─── Shared hook command ──────────────────────────────────────────────────────

/// A lifecycle hook command that works on the host *and* inside a sandbox,
/// from one compiled config. The compiler can't know at compile time
/// whether an agent will run sandboxed (the isolation tier is resolved
/// per-spawn), so the command branches at run time on `$SHIP_DAEMON_URL`:
///
/// - **In a sandbox** the supervisor injects `$SHIP_DAEMON_URL` (rewritten
///   to a container-reachable host) + a scoped `$SHIP_TOKEN`; the hook
///   `curl`s its harness-native payload straight at the daemon — no `ship`
///   CLI in the container. The daemon derives identity from the token and
///   deserializes the raw payload via `ShipHookEvent`'s field aliases.
/// - **On the host** `$SHIP_DAEMON_URL` is unset → the hook is a NO-OP
///   (`true`). No `hook` subcommand exists in ship-cli; a failing lifecycle
///   hook blocks the harness's turn-end and death-spirals the agent
///   (operator ruling 2026-07-06: emit nothing that can fail until the
///   hooks mechanism is redesigned).
///
/// Shared by every harness that emits command-style lifecycle hooks
/// (claude `.mcp`/settings, codex `hooks.json`). Note: `before-tool`
/// *blocking* is observability-only in the curl branch (raw curl can't
/// translate the daemon's allow/block into a harness hook-block protocol).
pub(super) fn ship_hook_command(endpoint: &str) -> String {
    format!(
        "if [ -n \"$SHIP_DAEMON_URL\" ]; then \
curl -sS -X POST \"$SHIP_DAEMON_URL/hooks/{endpoint}\" \
-H \"Authorization: Bearer $SHIP_TOKEN\" -H \"Content-Type: application/json\" \
--data-binary @- >/dev/null 2>&1; \
else true; fi"
    )
}

// ─── Output ───────────────────────────────────────────────────────────────────

/// The content generated by the compiler for a given harness.
/// All values are strings ready to write; no filesystem access required.
#[cfg_attr(feature = "specta", derive(specta::Type))]
#[derive(Debug, Clone, Default, serde::Serialize)]
pub struct CompileOutput {
    /// MCP server entries to inject into the target config file.
    /// Key = harness's `mcp_key` value, value = JSON object mapping server ID → entry.
    pub mcp_servers: Json,

    /// Project-relative path where the MCP config file should be written,
    /// e.g. `".mcp.json"` for Claude.
    /// `None` when the harness merges MCP into a larger settings file.
    pub mcp_config_path: Option<String>,

    /// Context file content (CLAUDE.md / AGENTS.md).
    /// `None` if the harness has no context file or there is no content to emit.
    pub context_content: Option<String>,

    /// Skill files: path relative to project root → file content.
    /// e.g. `".claude/skills/my-skill/SKILL.md" → "---\nname: my-skill\n..."`.
    pub skill_files: HashMap<String, String>,

    /// Claude settings patch: `permissions`, `hooks`, agent limits.
    /// Only populated for the `claude` harness.
    pub claude_settings_patch: Option<Json>,

    /// Codex config patch: `[mcp_servers.<id>]` TOML tables.
    /// Only populated for the `codex` harness.
    /// Merge into `.codex/config.toml`.
    pub codex_config_patch: Option<String>,

    /// Legacy cursor hooks file output. The cursor harness was removed; this
    /// field is retained for output-writer compatibility and is never populated.
    pub cursor_hooks_patch: Option<Json>,

    /// Legacy cursor CLI permissions output. The cursor harness was removed;
    /// this field is retained for output-writer compatibility and is never
    /// populated.
    pub cursor_cli_permissions: Option<Json>,

    /// Per-file rule output for harnesses that use individual rule files.
    /// Key = relative path, value = file content. No current harness emits
    /// per-file rules (cursor harness removed); other harnesses use
    /// `context_content`.
    pub rule_files: HashMap<String, String>,

    /// Plugin install intent declared by the active preset.
    /// This is a pure output artifact — the compiler never installs plugins.
    /// The CLI/runtime reads this after compilation and executes the lifecycle.
    pub plugins_manifest: PluginsManifest,

    /// Harness-native agent definition files.
    /// Key = path relative to project root (e.g. `.claude/agents/monitor.md`).
    /// Value = file content. Written verbatim by the CLI.
    pub agent_files: HashMap<String, String>,

    /// Legacy cursor environment output. The cursor harness was removed; this
    /// field is retained for output-writer compatibility and is never populated.
    pub cursor_environment_json: Option<Json>,

    /// Claude-only: `.claude/lsp.json` content registering the Ship LSP.
    pub claude_lsp_config: Option<Json>,

    /// OpenCode-only: full `opencode.json` content (model + MCP + extras).
    /// Only populated for the `opencode` harness.
    pub opencode_config_patch: Option<Json>,

    /// Codex-only: `.codex/hooks.json` content.
    /// Only populated for the `codex` harness.
    pub codex_hooks_json: Option<Json>,

    /// Codex-only: Starlark execpolicy content for `.codex/rules/ship.rules`.
    /// `None` means no rules to emit; the file should be deleted if it exists.
    pub codex_policy_content: Option<String>,

    /// Resolved actor event subscription namespaces for this agent.
    ///
    /// Combines:
    /// - `ship.{suffix}` entries inferred from skill artifact declarations.
    /// - `{skill.id}.` custom namespace for each skill.
    ///
    /// The runtime reads this at actor spawn time to replace the hardcoded
    /// `subscribe_namespaces` list in `ActorConfig`.
    pub event_subscriptions: Vec<String>,
}

// ─── Main entry point ─────────────────────────────────────────────────────────

/// Compile a resolved agent config into harness-ready content.
/// Returns `None` if the harness ID is not recognised.
pub fn compile(resolved: &ResolvedConfig, harness_id: &str) -> Option<CompileOutput> {
    let desc = get_harness(harness_id)?;
    let flags = desc.feature_flags();
    let mut out = CompileOutput::default();

    // Only emit MCP config for harnesses that support it.
    if flags.supports_mcp {
        // MCP builder is carried on the descriptor; all current harnesses
        // share mcp::build_mcp_servers.
        out.mcp_servers = (desc.build_mcp)(desc, &resolved.mcp_servers);
        out.mcp_config_path = desc.mcp_config_path.map(String::from);
    } else {
        out.mcp_servers = serde_json::json!({});
    }
    out.context_content = context::build_context_content(desc, resolved);
    out.skill_files = skills::build_skill_files(desc, resolved);
    out.event_subscriptions = skills::resolve_event_subscriptions(&resolved.skills);

    // Compile agent profiles for this harness
    let profile_agents = agents::compile_agent_profiles(&resolved.agent_profiles, harness_id);
    out.agent_files.extend(profile_agents);

    // Harness-native settings/policy/hook outputs — dispatched via the
    // descriptor's fn pointer, no harness-id branch. Runs after agent
    // profiles so claude's team-agent passthrough lands in out.agent_files.
    (desc.build_settings)(desc, resolved, &mut out);

    out.plugins_manifest = plugins::build_plugins_manifest(&resolved.plugins, harness_id);

    Some(out)
}
