//! Phase 9 — TypeScript declaration emission.
//!
//! Generates the `.d.ts` per `docs/sail/02-compiler-architecture.md
//! § Phase 9` so JSX consumers and direct DOM API users see the
//! custom-element's prop types and event payloads.

use crate::parse::ast::SailFile;

pub fn emit(file: &SailFile, tag: &str) -> String {
    let interface_name = pascal_of(tag);
    let mut out = String::new();
    out.push_str("// Auto-generated by Sail compiler. Do not edit.\n\n");
    out.push_str(&format!("export interface {interface_name} extends HTMLElement {{\n"));
    if let Some(s) = &file.script {
        for p in &s.props {
            let ty = p.ty.as_deref().unwrap_or("string");
            out.push_str(&format!("  {}: {};\n", p.name, ty));
        }
        for e in &s.events {
            let ty = e.payload_ty.as_deref().unwrap_or("unknown");
            out.push_str(&format!(
                "  addEventListener(type: {ev:?}, listener: (e: CustomEvent<{ty}>) => void): void;\n",
                ev = e.name,
            ));
        }
    }
    out.push_str("}\n\n");
    out.push_str("declare global {\n  interface HTMLElementTagNameMap {\n");
    out.push_str(&format!("    {tag:?}: {interface_name};\n"));
    out.push_str("  }\n}\n");
    out
}

fn pascal_of(tag: &str) -> String {
    let mut out = String::new();
    let mut up = true;
    for c in tag.chars() {
        if c == '-' { up = true; continue; }
        if up { out.push(c.to_ascii_uppercase()); up = false; }
        else { out.push(c); }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::parse;

    #[test]
    fn emits_props_and_events() {
        let src = "<script>prop label: string = 'x'\nevent select: { id: string }</script><template><div></div></template>";
        let file = parse::parse(src).unwrap();
        let dts = emit(&file, "sail-x");
        assert!(dts.contains("export interface SailX extends HTMLElement"));
        assert!(dts.contains("label: string;"));
        assert!(dts.contains("addEventListener(type: \"select\""));
        assert!(dts.contains("\"sail-x\": SailX"));
    }
}
