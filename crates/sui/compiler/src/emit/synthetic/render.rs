//! The **render** half of a synthetic view: the markup → DOM module.
//!
//! It imports the synthetic controller's typed `scope` and wires bindings
//! against it. Author expressions are rewritten with a `scope.` prefix so
//! `{route.params.id()}` compiles to `scope.route.params.id()` — resolved
//! against the controller's REAL, typed `scope` export, not the untyped
//! `$scope` proxy. That typing is what lets tsgo catch `scope.route.parms`
//! against `RouteSignals`.
//!
//! Unlike the desugar spike — which hand-rolled a minimal element/text
//! emitter — this REUSES the production [`TemplateEmitter`]. Driving the
//! same walk with a `"scope."` prefix is the whole point: every template
//! feature (`{#if/#for/#match/#while-*}`, `on:`, `bind:`, `class:`,
//! `style:`, slots, nested components) emits identically to production,
//! so the synthetic path inherits the emitter's full behavior for free.
//!
//! Two scope variables coexist in `mount()`:
//!   * `scope` — the typed import. Author expressions read `scope.X`, so
//!     tsgo checks them against the controller's `Scope` type.
//!   * `$scope` — the runtime-mutable scope (`Object.create(scope)`). The
//!     emitter's machinery (child scopes, per-row `__v` version signals,
//!     `bindWhileLoading({ signal: $scope.<data> })`) drives this. It
//!     inherits every member of `scope` through the prototype, so a
//!     machinery read of a `<data>` signal resolves to the same object an
//!     author read does — one source of truth, two reference paths.

use super::super::template_emit::TemplateEmitter;
use super::super::writer::{js_string, Writer};
use crate::bindings;
use crate::diagnostics::CompileError;
use crate::ir::*;
use crate::lower;
use crate::CompileMode;

const HEADER: &str = "\
// AUTO-GENERATED by sui-compiler `synthesize` — the RENDER half (markup →
// DOM). Do NOT edit. Bindings resolve against the synthetic controller's
// typed `scope` export, so member typos are tsgo/tsc type errors.";

const SCOPE_PREFIX: &str = "scope.";

/// Author-side runtime symbols that belong in the **controller**, not the
/// render. `lower` reports them in `runtime_imports`, but the render never
/// calls `view()`/`component()`/`data()`/`live()`/`prop()` — those lower
/// into the controller's logic half. Everything else `lower` reports is a
/// template binder the mount body uses.
const CONTROLLER_ONLY_IMPORTS: &[&str] = &["view", "component", "prop", "data", "live"];

/// Emit the render module. `controller_specifier` is the import path back
/// to the emitted synthetic controller. `mode` selects view vs component
/// lowering (used only to compute the runtime import set).
pub(super) fn emit_render(
    program: &Program,
    controller_specifier: &str,
    mode: CompileMode,
) -> Result<String, CompileError> {
    if let Some(err) = unsupported_feature(&program.template) {
        return Err(err);
    }

    // Reuse the production emitter with a `scope.` author-expression prefix.
    // `is_view = false`: the render mounts from scratch (no SSR-adoption
    // hydrate path), and the `is_view` gates only add hydrate-buffer calls,
    // never the mount DOM — so a component-mode emitter yields the clean
    // mount body + control-flow hoists we want.
    let registry = bindings::build(program);
    let mut emitter = TemplateEmitter::new(&registry, false).with_expr_prefix(SCOPE_PREFIX);

    let mut body_w = Writer::new();
    emitter.emit_top_level(&mut body_w, &program.template, "container", "__cleanups");

    let callbacks = emitter.take_render_callbacks();
    let hoists = emitter.take_boundary_hoists();
    // Mount-only: any hydrate-buffer content (is_view path) is unused here.
    let _ = emitter.take_hydrate_calls();

    let imports = render_runtime_imports(program, mode);

    let mut w = Writer::new();
    w.line(HEADER);
    if !imports.is_empty() {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-runtime\";",
            imports.join(", ")
        ));
    }
    w.line(&format!("import {{ scope }} from {};", js_string(controller_specifier)));
    w.nl();
    w.line("/** Build the view's DOM under `container`; returns a disposer. */");
    w.line("export function mount(container: HTMLElement): () => void {");
    w.enter();
    // `$scope` is the runtime-mutable scope the emitter machinery drives;
    // it inherits `scope`'s members so a machinery read of a `<data>`
    // signal resolves to the same object an author `scope.X` read does.
    // Typed `any` because the emitter adds ad-hoc props (`__v`, row binders).
    w.line("// eslint-disable-next-line @typescript-eslint/no-explicit-any");
    w.line("const $scope: any = Object.create(scope);");
    w.line("const __cleanups: Array<() => void> = [];");
    // Render callbacks ({#while-*}) and boundary hoists ({#if/#for/#match})
    // are referenced by name from the mount body, so they must be declared
    // before it. Both capture `$scope`.
    if !callbacks.is_empty() {
        w.push_str(&callbacks);
    }
    if !hoists.is_empty() {
        w.push_str(&hoists);
    }
    w.push_str(&body_w.into_string());
    w.line("return () => { for (const c of __cleanups) { try { c(); } catch (e) { /* dispose */ } } };");
    w.leave();
    w.line("}");
    Ok(w.into_string())
}

/// The runtime symbols the render imports from `@ship/sui-runtime`: the
/// template binders `lower` detected, minus the controller-only set.
fn render_runtime_imports(program: &Program, mode: CompileMode) -> Vec<String> {
    let lowered = lower::lower(program, mode);
    let mut imports: Vec<String> = lowered
        .runtime_imports
        .iter()
        .filter(|s| !CONTROLLER_ONLY_IMPORTS.contains(s))
        .map(|s| s.to_string())
        .collect();
    for &name in &lowered.transition_builtins {
        let s = name.to_string();
        if !imports.contains(&s) {
            imports.push(s);
        }
    }
    imports.sort();
    imports
}

/// Detect template features the synthetic render cannot yet emit correctly,
/// returning a hard error rather than mis-emitting. Today that is only
/// `{#async X as v}` (`Instr::Let`): it snapshots `$scope.<name> = value`,
/// but author body reads resolve through the typed `scope.<name>` — and
/// `<name>` is not a member of the controller's `Scope`, so the two
/// diverge. Phase 2 handles `{#async}` by lifting the binding into the
/// controller's typed scope; until then it is out of scope here.
fn unsupported_feature(instrs: &[Instr]) -> Option<CompileError> {
    for instr in instrs {
        let nested: Option<&[Instr]> = match instr {
            Instr::Let(_) => {
                return Some(
                    CompileError::new(
                        "synthesize: `{#async … as v}` is not supported in the synthetic \
                         render yet — its `as` binding isn't part of the controller's typed \
                         scope. (Phase 2: lift the binding into the typed scope.)",
                    )
                    .with_category("synthesize"),
                );
            }
            Instr::Element(el) => Some(&el.children),
            Instr::If(i) => {
                for b in &i.branches {
                    if let Some(e) = unsupported_feature(&b.body) {
                        return Some(e);
                    }
                }
                i.else_body.as_deref()
            }
            Instr::For(f) => {
                if let Some(e) = unsupported_feature(&f.body) {
                    return Some(e);
                }
                f.else_body.as_deref()
            }
            Instr::Match(m) => {
                for c in &m.cases {
                    if let Some(e) = unsupported_feature(&c.body) {
                        return Some(e);
                    }
                }
                m.default.as_deref()
            }
            Instr::WhileLoading(wl) => Some(&wl.body),
            Instr::WhileError(we) => Some(&we.body),
            _ => None,
        };
        if let Some(children) = nested
            && let Some(e) = unsupported_feature(children)
        {
            return Some(e);
        }
    }
    None
}
