//! Substrate-fn index generation helper for `cargo xtask gen-indexes`.
//!
//! Collects every `pub fn`, `pub async fn`, `pub const fn` declaration in
//! `crates/core/ship-substrate/src/` and `crates/core/ship-platform/src/`,
//! excluding test files and `#[cfg(test)]` blocks.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use regex::Regex;

const SUBSTRATE_FNS_PATH: &str =
    ".artifacts/specs/op-surface-audit/_indexes/substrate-fns.md";

const SUBSTRATE_ROOTS: &[(&str, &str)] = &[
    ("crates/core/ship-substrate/src", "ship-substrate"),
    ("crates/core/ship-platform/src", "ship-platform"),
];

pub struct SubstrateFn {
    pub rel_path: String,
    pub line: usize,
    pub signature: String,
    pub doc: String,
    pub rw: String,
}

pub fn index_path() -> &'static str {
    SUBSTRATE_FNS_PATH
}

pub fn collect(repo_root: &Path) -> Result<Vec<SubstrateFn>> {
    let pub_fn_re = Regex::new(
        r"^\s*pub\s+(?:async\s+|const\s+)?fn\s+(\w+)\s*[<(]"
    )?;

    let mut fns: Vec<SubstrateFn> = Vec::new();

    for &(root_str, _crate_name) in SUBSTRATE_ROOTS {
        let root = repo_root.join(root_str);
        let mut files = Vec::new();
        walk_rs_files(&root, &mut files)?;

        for file_path in &files {
            let rel_path = file_path
                .strip_prefix(repo_root)
                .unwrap_or(file_path)
                .to_string_lossy()
                .to_string();

            let content = std::fs::read_to_string(file_path)
                .context(format!("read {}", file_path.display()))?;

            let found = extract_pub_fns(&content, &rel_path, &pub_fn_re)?;
            fns.extend(found);
        }
    }

    fns.sort_by(|a, b| a.rel_path.cmp(&b.rel_path).then(a.line.cmp(&b.line)));
    Ok(fns)
}

pub fn render(fns: &[SubstrateFn]) -> String {
    let mut out = String::new();

    let substrate_count = fns.iter().filter(|f| f.rel_path.contains("ship-substrate")).count();
    let platform_count = fns.iter().filter(|f| f.rel_path.contains("ship-platform")).count();

    out.push_str("# Substrate fn index\n\n");
    out.push_str("Generated by `cargo xtask gen-indexes`. Every row cites file:line. \
Use this as the citation source for any downstream \"missing op\" or \"substrate capability\" claim.\n\n");
    out.push_str(&format!("**Total pub fns:** {}\n", fns.len()));
    out.push_str(&format!(
        "**By crate:** ship-substrate {} · ship-platform {}\n\n",
        substrate_count, platform_count
    ));
    out.push_str("Scope: `pub fn`, `pub async fn`, `pub const fn` in source modules under \
`crates/core/ship-substrate/src/` and `crates/core/ship-platform/src/`. \
Test files (`tests.rs`, `*_tests.rs`, `tests_*.rs`, `tests/`) and `#[cfg(test)]` blocks excluded. \
`pub(crate)` and `pub(super)` excluded.\n");

    let mut groups: BTreeMap<(String, String), Vec<&SubstrateFn>> = BTreeMap::new();
    for f in fns {
        let (crate_name, module_path) = classify_module(&f.rel_path);
        groups.entry((crate_name, module_path)).or_default().push(f);
    }

    for ((crate_name, module_path), group) in &groups {
        out.push_str(&format!("\n## {} / {}\n\n", crate_name, module_path));
        out.push_str(&format!("`crates/core/{}/src/{}`\n\n", crate_name, module_path));
        out.push_str("| Fn | file:line | Doc | R/W |\n");
        out.push_str("|---|---|---|---|\n");
        for f in group.iter() {
            let doc: String = f.doc.chars().take(80).collect();
            out.push_str(&format!(
                "| `{}` | `{}:{}` | {} | {} |\n",
                f.signature, f.rel_path, f.line, doc, f.rw
            ));
        }
    }

    out
}

// ── File walker ───────────────────────────────────────────────────────────────

pub fn walk_rs_files(dir: &Path, out: &mut Vec<PathBuf>) -> Result<()> {
    if !dir.is_dir() {
        return Ok(());
    }
    for entry in std::fs::read_dir(dir)
        .context(format!("read_dir {}", dir.display()))?
    {
        let entry = entry?;
        let path = entry.path();
        let name = path.file_name().and_then(|n| n.to_str()).unwrap_or("");
        if path.is_dir() {
            if matches!(name, "target" | "tests" | "fuzz" | "examples") {
                continue;
            }
            walk_rs_files(&path, out)?;
        } else if name.ends_with(".rs") {
            if !is_test_file(name) {
                out.push(path);
            }
        }
    }
    Ok(())
}

pub fn is_test_file(name: &str) -> bool {
    name == "tests.rs"
        || name.ends_with("_tests.rs")
        || name.starts_with("tests_")
}

// ── Extraction ────────────────────────────────────────────────────────────────

fn extract_pub_fns(
    content: &str,
    rel_path: &str,
    pub_fn_re: &Regex,
) -> Result<Vec<SubstrateFn>> {
    let mut fns = Vec::new();
    let lines: Vec<&str> = content.lines().collect();
    let mut in_cfg_test = 0usize;
    let mut prev_doc = String::new();

    for (idx, &line) in lines.iter().enumerate() {
        let lineno = idx + 1;
        let trimmed = line.trim();

        if trimmed.contains("#[cfg(test)]") {
            in_cfg_test += 1;
        }
        if trimmed == "}" && line.starts_with('}') && in_cfg_test > 0 {
            in_cfg_test = in_cfg_test.saturating_sub(1);
        }
        if in_cfg_test > 0 {
            prev_doc.clear();
            continue;
        }

        // Skip pub(crate), pub(super), pub(in path).
        if trimmed.contains("pub(") {
            prev_doc.clear();
            continue;
        }

        // Accumulate doc comments.
        if trimmed.starts_with("///") {
            let doc_text = trimmed.trim_start_matches('/').trim();
            if !prev_doc.is_empty() {
                prev_doc.push(' ');
            }
            prev_doc.push_str(doc_text);
        }

        if pub_fn_re.is_match(line) {
            let sig = build_signature(&lines, idx);
            let rw = classify_rw(content, lineno);

            fns.push(SubstrateFn {
                rel_path: rel_path.to_string(),
                line: lineno,
                signature: sig,
                doc: prev_doc.clone(),
                rw,
            });
            prev_doc.clear();
        } else if !trimmed.starts_with("///") && !trimmed.starts_with('#') && !trimmed.is_empty() {
            prev_doc.clear();
        }
    }

    Ok(fns)
}

fn build_signature(lines: &[&str], start: usize) -> String {
    let mut sig = lines[start].trim().to_string();
    let mut depth = sig.chars().filter(|&c| c == '(').count() as i32
        - sig.chars().filter(|&c| c == ')').count() as i32;
    let mut i = start + 1;
    while depth > 0 && i < lines.len() && i < start + 6 {
        let next = lines[i].trim();
        sig.push(' ');
        sig.push_str(next);
        depth += next.chars().filter(|&c| c == '(').count() as i32;
        depth -= next.chars().filter(|&c| c == ')').count() as i32;
        i += 1;
    }
    if let Some(pos) = sig.find(" {") {
        sig.truncate(pos);
    }
    if sig.len() > 120 {
        sig.truncate(117);
        sig.push_str("…");
    }
    sig
}

fn classify_rw(content: &str, lineno: usize) -> String {
    let lines: Vec<&str> = content.lines().collect();
    let start = lineno.saturating_sub(1);
    let end = std::cmp::min(start + 30, lines.len());
    let body: String = lines[start..end].join("\n");

    let sig_line = lines.get(start).copied().unwrap_or("");
    if sig_line.contains("&mut self")
        || body.contains("EventEnvelope::new(")
        || body.contains(".emit(")
    {
        return "[W]".to_string();
    }
    if sig_line.contains("&self") && !sig_line.contains("Result<()>") {
        return "[R]".to_string();
    }
    "[?]".to_string()
}

fn classify_module(rel_path: &str) -> (String, String) {
    let crate_name = if rel_path.contains("ship-substrate") {
        "ship-substrate"
    } else {
        "ship-platform"
    };

    let after_src = rel_path
        .find("/src/")
        .map(|i| &rel_path[i + 5..])
        .unwrap_or(rel_path);

    let module_path = if let Some(pos) = after_src.rfind('/') {
        after_src[..pos].to_string()
    } else {
        "(root)".to_string()
    };

    (crate_name.to_string(), module_path)
}
