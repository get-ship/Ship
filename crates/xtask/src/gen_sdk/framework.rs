//! Emit the framework manifest as both JSON and TypeScript.
//!
//! - `packages/ship-set/sdk/sdk-framework.json` — tooling/agent-prompt
//!   consumption. Sits alongside the other generated SDK artefacts.
//! - `packages/sdk/src/generated/framework.ts` — typed
//!   `FrameworkManifest` interface + `FRAMEWORK` const for IDE-side
//!   consumers.
//!
//! The Rust compiler in `sail-compiler` owns the canonical manifest
//! shape (`sail_compiler::manifest::emit()`); this module adapts the
//! output to the two file formats the SDK pipeline cares about and
//! also walks the corpus of `.set` files under
//! `packages/ship-set-sail/components/` to populate the per-component
//! prop catalog. The compiler crate intentionally doesn't see the
//! corpus directly — that's the gen-sdk pipeline's job.

use std::path::Path;

use anyhow::{Context, Result};
use sail_compiler::manifest::{self, Component, ComponentProp, Manifest};
use sail_compiler::{parse, tag_for_stem};
use serde_json::Value;

const TS_HEADER: &str = "// @generated by `cargo xtask gen-sdk` from \
                         crates/sail-compiler/src/manifest.rs — DO NOT EDIT.\n\
                         // Run `cargo xtask gen-sdk` after editing the manifest \
                         to regenerate.\n";

/// Build the manifest with the corpus walked and `components`
/// populated. Used by both the JSON and TS emitters so the two files
/// stay in lockstep.
pub fn manifest_with_components(repo_root: &Path) -> Result<Manifest> {
    let mut m = manifest::emit();
    m.components = collect_components(repo_root)?;
    Ok(m)
}

/// Build the JSON value written to `sdk-framework.json`. The
/// envelope (`_generated`/`version`/`$schema`) is added by the
/// caller in `gen_sdk::write_framework`.
pub fn json_entries(repo_root: &Path) -> Result<Value> {
    let m = manifest_with_components(repo_root)?;
    Ok(serde_json::to_value(&m)?)
}

pub fn manifest_version() -> &'static str {
    manifest::MANIFEST_VERSION
}

/// Emit the TypeScript file. Types live next to the typed const so a
/// single import gives consumers both the shape and the data.
pub fn emit_ts(repo_root: &Path) -> Result<String> {
    let m = manifest_with_components(repo_root)?;
    let mut out = String::new();
    out.push_str(TS_HEADER);
    out.push('\n');
    out.push_str(TS_TYPES);
    out.push('\n');
    out.push_str("export const FRAMEWORK: FrameworkManifest = ");
    out.push_str(&serde_json::to_string_pretty(&m)?);
    out.push_str(";\n");
    Ok(out)
}

/// Walk `packages/ship-set-sail/components/*.set`, parse each, and
/// pull `(tag, props, description)` for each one. Returns components
/// sorted by tag for deterministic output.
fn collect_components(repo_root: &Path) -> Result<Vec<Component>> {
    let dir = repo_root.join("packages/ship-set-sail/components");
    let mut entries: Vec<_> = std::fs::read_dir(&dir)
        .with_context(|| format!("read_dir {}", dir.display()))?
        .filter_map(|e| e.ok())
        .map(|e| e.path())
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("set"))
        .collect();
    entries.sort();

    let mut out = Vec::with_capacity(entries.len());
    for path in entries {
        let stem = path
            .file_stem()
            .and_then(|s| s.to_str())
            .unwrap_or_default();
        let tag = tag_for_stem(stem);
        let source = std::fs::read_to_string(&path)
            .with_context(|| format!("read {}", path.display()))?;
        let file = match parse::parse(&source) {
            Ok(f) => f,
            Err(err) => {
                eprintln!(
                    "gen-sdk framework: skipping {} (parse failed: {err})",
                    path.display()
                );
                continue;
            }
        };
        let (script_raw, props): (Option<&str>, Vec<ComponentProp>) = match file.script.as_ref() {
            Some(script) => (
                Some(script.raw.as_str()),
                script
                    .props
                    .iter()
                    .map(|p| ComponentProp {
                        name: p.name.clone(),
                        ty: p.ty.clone().unwrap_or_else(|| "unknown".into()),
                        required: p.required,
                    })
                    .collect(),
            ),
            None => (None, Vec::new()),
        };
        let description = script_raw
            .and_then(leading_comment_block)
            .unwrap_or_else(|| tag.clone());
        out.push(Component {
            tag,
            props,
            description,
        });
    }
    Ok(out)
}

/// Pull the leading `// …` comment block off a script body. Stops at
/// the first non-comment, non-blank line. Returns `None` when the
/// body has no leading comment.
fn leading_comment_block(script_raw: &str) -> Option<String> {
    let mut lines = Vec::new();
    let mut saw_any = false;
    for line in script_raw.lines() {
        let t = line.trim();
        if t.is_empty() {
            if saw_any {
                break;
            }
            continue;
        }
        if let Some(rest) = t.strip_prefix("//") {
            saw_any = true;
            lines.push(rest.trim_start().to_string());
        } else {
            break;
        }
    }
    if lines.is_empty() {
        None
    } else {
        Some(lines.join("\n").trim().to_string())
    }
}

const TS_TYPES: &str = r#"export interface AntiExample {
  code: string;
  reason: string;
}

export interface Directive {
  name: string;
  kind: string;
  syntax: string;
  description: string;
  examples?: string[];
  anti_examples?: AntiExample[];
}

export interface ScopeBinding {
  name: string;
  type: string;
  available_in: string[];
  description: string;
}

export interface LifecycleHook {
  name: string;
  syntax: string;
  fires: string;
  description: string;
}

export interface TemplateSyntax {
  name: string;
  syntax: string;
  description: string;
  examples?: string[];
}

export interface ReactivityRule {
  id: string;
  name: string;
  description: string;
  anti_example: string;
  fix_example: string;
}

export interface ComponentProp {
  name: string;
  type: string;
  required: boolean;
}

export interface Component {
  tag: string;
  props: ComponentProp[];
  description: string;
}

export interface FrameworkManifest {
  version: string;
  directives: Directive[];
  scope_bindings: ScopeBinding[];
  lifecycle_hooks: LifecycleHook[];
  template_syntax: TemplateSyntax[];
  reactivity_rules: ReactivityRule[];
  components: Component[];
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .expect("cannot locate repo root")
            .to_path_buf()
    }

    #[test]
    fn json_entries_round_trips_to_manifest() {
        let v = json_entries(&repo_root()).unwrap();
        let m: Manifest = serde_json::from_value(v).unwrap();
        assert!(!m.directives.is_empty());
        assert_eq!(m.version, manifest_version());
        assert!(!m.components.is_empty(), "components should be populated");
    }

    #[test]
    fn ts_emits_typed_const_and_types() {
        let ts = emit_ts(&repo_root()).unwrap();
        assert!(ts.contains("export interface FrameworkManifest"));
        assert!(ts.contains("export const FRAMEWORK: FrameworkManifest"));
        assert!(ts.contains("\"version\": \"0.2.0\""));
        assert!(ts.contains("export interface Component"));
        assert!(ts.contains("\"tag\": \"ship-button\""));
    }

    #[test]
    fn corpus_includes_known_components() {
        let m = manifest_with_components(&repo_root()).unwrap();
        let tags: Vec<&str> = m.components.iter().map(|c| c.tag.as_str()).collect();
        for required in ["ship-button", "ship-card", "ship-input", "ship-accordion"] {
            assert!(tags.contains(&required), "missing {required} in {tags:?}");
        }
        let button = m
            .components
            .iter()
            .find(|c| c.tag == "ship-button")
            .unwrap();
        let names: Vec<&str> = button.props.iter().map(|p| p.name.as_str()).collect();
        for prop in ["tone", "variant", "size", "disabled"] {
            assert!(names.contains(&prop), "ship-button missing prop {prop}");
        }
    }

    #[test]
    fn leading_comment_block_extracts() {
        let raw = "// first line\n// second line\n\nprop x = 1\n";
        assert_eq!(
            leading_comment_block(raw),
            Some("first line\nsecond line".into())
        );
        assert_eq!(leading_comment_block("prop x = 1\n"), None);
    }
}
