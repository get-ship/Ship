fn template_syntax() -> Value {
    json!([
        { "name": "interpolation", "syntax": "{expr}",
          "description": "Restricted expression: identifier reads, member access, basic operators, ternary, template literals, function calls. No statements/assignments/arrows." },
        { "name": "attribute binding", "syntax": "name={expr}",
          "description": "Plain attribute reactivity. `null`/`undefined` → attribute omitted." }
    ])
}

fn reactivity_rules() -> Value {
    json!([
        { "id": "no-arrow-in-template", "name": "No arrow functions in template expressions",
          "description": "Template expressions are restricted; arrows belong in setup .ts.",
          "anti_example": "<button on:click={() => count.set(count() + 1)}>",
          "fix_example": "function inc() { count.set(count() + 1) }  /* in setup */ on:click={inc}" }
    ])
}

/// Build the JSON value written to `sdk-framework.json`.
pub fn json_entries(_repo_root: &Path) -> Result<Value> {
    Ok(json!({
        "version":        manifest_version(),
        "directives":     directives(),
        "scope_bindings": scope_bindings(),
        "template_syntax": template_syntax(),
        "reactivity_rules": reactivity_rules(),
        "lifecycle_hooks": [],
        "components":     []
    }))
}

/// Emit the TypeScript file.
pub fn emit_ts(_repo_root: &Path) -> Result<String> {
    let mut out = String::new();
    out.push_str(TS_HEADER);
    out.push('\n');
    out.push_str(TS_TYPES);
    out.push('\n');
    out.push_str("export const FRAMEWORK: FrameworkManifest = ");
    out.push_str(&serde_json::to_string_pretty(&json!({
        "version":         manifest_version(),
        "directives":      directives(),
        "scope_bindings":  scope_bindings(),
        "template_syntax": template_syntax(),
        "reactivity_rules": reactivity_rules(),
        "lifecycle_hooks": [],
        "components":      []
    }))?);
    out.push_str(";\n");
    Ok(out)
}

const TS_TYPES: &str = r#"export interface AntiExample {
  code: string;
  reason: string;
}

export interface Directive {
  name: string;
  kind: string;
  syntax: string;
  description: string;
  examples?: string[];
  anti_examples?: AntiExample[];
}

export interface ScopeBinding {
  name: string;
  type: string;
  available_in: string[];
  description: string;
}

export interface LifecycleHook {
  name: string;
  syntax: string;
  fires: string;
  description: string;
}

export interface TemplateSyntax {
  name: string;
  syntax: string;
  description: string;
  examples?: string[];
}

export interface ReactivityRule {
  id: string;
  name: string;
  description: string;
  anti_example: string;
  fix_example: string;
}

export interface ComponentProp {
  name: string;
  type: string;
  required: boolean;
}

export interface Component {
  tag: string;
  props: ComponentProp[];
  description: string;
}

export interface FrameworkManifest {
  version: string;
  directives: Directive[];
  scope_bindings: ScopeBinding[];
  lifecycle_hooks: LifecycleHook[];
  template_syntax: TemplateSyntax[];
  reactivity_rules: ReactivityRule[];
  components: Component[];
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .expect("cannot locate repo root")
            .to_path_buf()
    }

    #[test]
    fn manifest_carries_real_directives() {
        let v = json_entries(&repo_root()).unwrap();
        let directives = v.get("directives").and_then(|d| d.as_array()).unwrap();
        assert!(directives.iter().any(|d| d["name"] == "data"));
        assert!(directives.iter().any(|d| d["name"] == "while-loading"));
        assert!(directives.iter().any(|d| d["name"] == "match"));
    }

    #[test]
    fn ts_emits_typed_const_and_types() {
        let ts = emit_ts(&repo_root()).unwrap();
        assert!(ts.contains("export interface FrameworkManifest"));
        assert!(ts.contains("export const FRAMEWORK: FrameworkManifest"));
        assert!(ts.contains("export interface Component"));
    }

    #[test]
    fn version_is_real() {
        assert_ne!(manifest_version(), "0.0.0-stub");
        assert!(manifest_version().contains('.'));
    }
}
