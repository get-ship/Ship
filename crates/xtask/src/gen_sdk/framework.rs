//! Emit the framework manifest as both JSON and TypeScript.
//!
//! - `packages/ship-set/sdk/sdk-framework.json` — tooling/agent-prompt
//!   consumption. Sits alongside the other generated SDK artefacts.
//! - `packages/sdk/src/generated/framework.ts` — typed
//!   `FrameworkManifest` interface + `FRAMEWORK` const for IDE-side
//!   consumers.
//!
//! TODO(Phase 4): The Rust compiler in `ship-set-compiler` will own the
//! canonical manifest shape; this module will adapt its output to the two
//! file formats the SDK pipeline cares about and walk the corpus of `.set`
//! files under `packages/ship-set/components/` to populate the per-component
//! prop catalog. Until ship-set-compiler is available, `json_entries` and
//! `emit_ts` return stub values so `cargo xtask gen-sdk` still runs without
//! error — the emitted files carry a `_stub: true` marker so consumers know
//! not to rely on their content yet.

use std::path::Path;

use anyhow::Result;
use serde_json::Value;

const TS_HEADER: &str = "// @generated by `cargo xtask gen-sdk` — DO NOT EDIT.\n\
                         // TODO(Phase 4): ship-set-compiler will populate this file.\n";

/// Version stub — will be replaced by the real manifest version once
/// ship-set-compiler provides it in Phase 4.
pub fn manifest_version() -> &'static str {
    "0.0.0-stub"
}

/// Build the JSON value written to `sdk-framework.json`.
/// TODO(Phase 4): replace stub with real manifest from ship-set-compiler.
pub fn json_entries(_repo_root: &Path) -> Result<Value> {
    Ok(serde_json::json!({
        "_stub": true,
        "note": "ship-set-compiler not yet available; real manifest will be generated in Phase 4",
        "directives": [],
        "scope_bindings": [],
        "lifecycle_hooks": [],
        "template_syntax": [],
        "reactivity_rules": [],
        "components": []
    }))
}

/// Emit the TypeScript file.
/// TODO(Phase 4): replace stub with real manifest const from ship-set-compiler.
pub fn emit_ts(_repo_root: &Path) -> Result<String> {
    let mut out = String::new();
    out.push_str(TS_HEADER);
    out.push('\n');
    out.push_str(TS_TYPES);
    out.push('\n');
    out.push_str("// TODO(Phase 4): FRAMEWORK const will be populated by ship-set-compiler.\n");
    out.push_str("export const FRAMEWORK: FrameworkManifest = ");
    out.push_str(&serde_json::to_string_pretty(&serde_json::json!({
        "version": "0.0.0-stub",
        "directives": [],
        "scope_bindings": [],
        "lifecycle_hooks": [],
        "template_syntax": [],
        "reactivity_rules": [],
        "components": []
    }))?);
    out.push_str(";\n");
    Ok(out)
}

const TS_TYPES: &str = r#"export interface AntiExample {
  code: string;
  reason: string;
}

export interface Directive {
  name: string;
  kind: string;
  syntax: string;
  description: string;
  examples?: string[];
  anti_examples?: AntiExample[];
}

export interface ScopeBinding {
  name: string;
  type: string;
  available_in: string[];
  description: string;
}

export interface LifecycleHook {
  name: string;
  syntax: string;
  fires: string;
  description: string;
}

export interface TemplateSyntax {
  name: string;
  syntax: string;
  description: string;
  examples?: string[];
}

export interface ReactivityRule {
  id: string;
  name: string;
  description: string;
  anti_example: string;
  fix_example: string;
}

export interface ComponentProp {
  name: string;
  type: string;
  required: boolean;
}

export interface Component {
  tag: string;
  props: ComponentProp[];
  description: string;
}

export interface FrameworkManifest {
  version: string;
  directives: Directive[];
  scope_bindings: ScopeBinding[];
  lifecycle_hooks: LifecycleHook[];
  template_syntax: TemplateSyntax[];
  reactivity_rules: ReactivityRule[];
  components: Component[];
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    fn repo_root() -> std::path::PathBuf {
        std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .and_then(|p| p.parent())
            .expect("cannot locate repo root")
            .to_path_buf()
    }

    #[test]
    fn json_entries_returns_stub() {
        let v = json_entries(&repo_root()).unwrap();
        assert_eq!(v.get("_stub"), Some(&Value::Bool(true)));
    }

    #[test]
    fn ts_emits_typed_const_and_types() {
        let ts = emit_ts(&repo_root()).unwrap();
        assert!(ts.contains("export interface FrameworkManifest"));
        assert!(ts.contains("export const FRAMEWORK: FrameworkManifest"));
        assert!(ts.contains("export interface Component"));
    }
}
