//! Emit `packages/deck/sdk/src/generated/data.ts` — typed TypeScript bindings
//! for the `ship.<domain>.<op>` data surface, generated from the same
//! `services::schema::OPS` catalog the Jinja SDK reads.
//!
//! Phase 1: type signatures + path union + descriptor map. Returns are
//! `unknown` until phase 3 threads real return shapes through.

use std::collections::{BTreeMap, BTreeSet};

use anyhow::Result;
use shipd::services::schema::{ArgDescriptor, OpDescriptor, OPS};

const HEADER: &str = "// @generated by `cargo xtask gen-sdk` from \
                      apps/shipd/src/services/schema.rs::OPS — DO NOT EDIT.\n\
                      // Run `cargo xtask gen-sdk` after editing OPS to regenerate.\n";

/// Return-type names that are real, specta-exported types in `../generated.ts`
/// (registered in `xtask::collect_types`). For these ops `data.ts` emits
/// `DataHandle<TypeName>` and imports the type; every other op keeps
/// `DataHandle<unknown>` (additive, non-breaking — an unmigrated domain is
/// simply still untyped). This list mirrors the typed-op return registrations
/// in `collect_types`; the two move together as domains migrate.
const MIGRATED_RETURN_TYPES: &[&str] = &[
];

/// The TS type a handle resolves to: a migrated named type, or `unknown`.
fn handle_type(returns: &str) -> &str {
    if MIGRATED_RETURN_TYPES.contains(&returns) {
        returns
    } else {
        "unknown"
    }
}

pub fn emit() -> Result<String> {
    let mut by_domain: BTreeMap<&'static str, Vec<&'static OpDescriptor>> = BTreeMap::new();
    for op in OPS.iter() {
        let domain = op.name.split('.').next().unwrap_or(op.name);
        by_domain.entry(domain).or_default().push(op);
    }

    // Collect the migrated return types actually used, so we import exactly
    // those from the specta-generated `../generated.ts`.
    let mut imports: BTreeSet<&'static str> = BTreeSet::new();
    for op in OPS.iter() {
        let ty = handle_type(op.returns);
        if ty != "unknown" {
            imports.insert(ty);
        }
    }

    let mut out = String::new();
    out.push_str(HEADER);
    out.push('\n');
    if !imports.is_empty() {
        out.push_str("import type {\n");
        for ty in &imports {
            out.push_str(&format!("  {ty},\n"));
        }
        out.push_str("} from '../generated';\n\n");
    }
    out.push_str(PRELUDE);
    out.push('\n');

    out.push_str("export type ShipDataPath =\n");
    let mut paths: Vec<&str> = OPS.iter().map(|op| op.name).collect();
    paths.sort();
    for (i, path) in paths.iter().enumerate() {
        let term = if i + 1 == paths.len() { ";" } else { "" };
        out.push_str(&format!("  | '{path}'{term}\n"));
    }
    out.push('\n');

    out.push_str("export interface ShipData {\n");
    for (domain, ops) in &by_domain {
        out.push_str(&format!("  {domain}: {{\n"));
        for op in ops {
            let local = op.name.split('.').nth(1).unwrap_or(op.name);
            let safe = ts_safe_name(local);
            let key = if safe == local { local.to_string() } else { format!("'{local}'") };
            let args_sig = render_args_sig(op.args);
            out.push_str(&render_op_jsdoc(op));
            let ret = handle_type(op.returns);
            out.push_str(&format!("    {key}({args_sig}): DataHandle<{ret}>;\n"));
            if safe != local {
                // Bracket-access friendly alias for callers who can't use the quoted form.
                let _ = safe;
            }
        }
        out.push_str("  };\n");
    }
    out.push_str("}\n\n");

    out.push_str("export interface OpMeta {\n");
    out.push_str("  readonly name: ShipDataPath;\n");
    out.push_str("  readonly description: string;\n");
    out.push_str("  readonly args: ReadonlyArray<{ name: string; kind: string; required: boolean }>;\n");
    out.push_str("  readonly returns: string;\n");
    out.push_str("  readonly permission: string;\n");
    out.push_str("  readonly sensitive: boolean;\n");
    out.push_str("}\n\n");

    out.push_str("export const SHIP_OPS_META: Readonly<Record<ShipDataPath, OpMeta>> = {\n");
    for path in &paths {
        let op = OPS.iter().find(|o| o.name == *path).expect("path is from OPS");
        out.push_str(&format!("  '{path}': {{\n"));
        out.push_str(&format!("    name: '{path}',\n"));
        out.push_str(&format!("    description: {},\n", quote_ts(op.description)));
        out.push_str("    args: [");
        if op.args.is_empty() {
            out.push_str("],\n");
        } else {
            out.push('\n');
            for arg in op.args {
                out.push_str(&format!(
                    "      {{ name: '{}', kind: '{}', required: {} }},\n",
                    arg.name, arg.kind, arg.required
                ));
            }
            out.push_str("    ],\n");
        }
        out.push_str(&format!("    returns: {},\n", quote_ts(op.returns)));
        out.push_str(&format!("    permission: '{}',\n", op.permission));
        out.push_str(&format!("    sensitive: {},\n", op.sensitive));
        out.push_str("  },\n");
    }
    out.push_str("};\n");

    Ok(out)
}

fn render_args_sig(args: &'static [ArgDescriptor]) -> String {
    if args.is_empty() {
        return String::new();
    }
    let all_optional = args.iter().all(|a| !a.required);
    let mut fields = String::new();
    for arg in args {
        let opt = if arg.required { "" } else { "?" };
        let ty = ts_type_for(arg.kind);
        fields.push_str(&format!("{}{opt}: {ty}; ", arg.name, ));
    }
    let suffix = if all_optional { "?" } else { "" };
    format!("args{suffix}: {{ {}}}", fields)
}

fn ts_type_for(kind: &str) -> &'static str {
    match kind.trim_end_matches('?') {
        "string" => "string",
        "number" | "usize" | "u64" | "i64" | "u32" | "i32" => "number",
        "bool" | "boolean" => "boolean",
        _ => "unknown",
    }
}

/// Render a JSDoc block for one op: one-line description plus a
/// matching `.set` declaration + minimal template usage as an
/// `@example`. The example is what an author would write to consume
/// the op from a `.set` file.
fn render_op_jsdoc(op: &OpDescriptor) -> String {
    let domain = op.name.split('.').next().unwrap_or(op.name);
    let local = op.name.split('.').nth(1).unwrap_or(op.name);
    let var = example_var_name(domain, local);
    let args_src = render_set_call_args(op.args);
    let usage = render_template_usage(&var, op.returns);

    let mut s = String::new();
    s.push_str("    /**\n");
    s.push_str(&format!("     * {}\n", op.description));
    s.push_str("     *\n");
    s.push_str("     * @example\n");
    s.push_str("     * ```html\n");
    s.push_str("     * <script>\n");
    s.push_str(&format!(
        "     *   data {var} = ship.{domain}.{local}({args_src})\n"
    ));
    s.push_str("     * </script>\n");
    s.push_str("     * <template>\n");
    s.push_str(&usage);
    s.push_str("     * </template>\n");
    s.push_str("     * ```\n");
    s.push_str("     */\n");
    s
}

/// Pick a readable identifier to bind the `data` declaration to.
/// Defaults to the domain name (so the example reads like idiomatic
/// `.set` code: `data agents = ship.agents.summaries()`). The `_` here
/// stays unused but documents the intent — this function is the seam
/// where future per-op renaming would live.
fn example_var_name(domain: &str, _local: &str) -> String {
    domain.to_string()
}

/// Render the args object literal an author would write in a `.set`
/// data declaration. Required-only — optional args are elided so the
/// example shows the minimum viable call.
fn render_set_call_args(args: &'static [ArgDescriptor]) -> String {
    let required: Vec<&ArgDescriptor> = args.iter().filter(|a| a.required).collect();
    if required.is_empty() {
        return String::new();
    }
    let parts: Vec<String> = required
        .iter()
        .map(|a| {
            let val = sample_arg_literal(a.kind, a.name);
            format!("{}: {val}", a.name)
        })
        .collect();
    format!("{{ {} }}", parts.join(", "))
}

fn sample_arg_literal(kind: &str, name: &str) -> String {
    match kind.trim_end_matches('?') {
        "string" => format!("'{}'", string_placeholder(name)),
        "number" | "usize" | "u64" | "i64" | "u32" | "i32" => "1".to_string(),
        "bool" | "boolean" => "true".to_string(),
        _ => "null".to_string(),
    }
}

fn string_placeholder(name: &str) -> &'static str {
    match name {
        "id" => "id",
        "name" => "name",
        "slug" => "slug",
        "path" => "src/foo.rs",
        "file" => "src/foo.rs",
        "commit" => "HEAD",
        "workspace_id" => "ws",
        _ => "value",
    }
}

/// Render a minimal template-side usage block. Branches on the shape
/// hinted by `returns`:
///   - `{items: [...]}` and other `{<key>: [...]}` shapes → for-loop
///   - `{<key>, ...}` flat record → read the first field
///   - named type → guarded read of the bound signal
fn render_template_usage(var: &str, returns: &str) -> String {
    let r = returns.trim();
    if let Some((key, is_list)) = first_record_field(r) {
        if is_list {
            return format!(
                "     *   {{#for item of ({var}()?.{key} || [])}}\n     *     <div>{{item.id || item.name || item}}</div>\n     *   {{/for}}\n",
            );
        }
        return format!("     *   <div>{{ {var}()?.{key} }}</div>\n");
    }
    // Named type — we don't know the shape. Show the read pattern.
    format!("     *   <pre>{{ JSON.stringify({var}(), null, 2) }}</pre>\n")
}

/// Parse the first field of an inline record like `{key: [...]}` or
/// `{a, b, c}`. Returns `(field_name, is_list)`.
fn first_record_field(s: &str) -> Option<(&str, bool)> {
    let s = s.trim();
    let inner = s.strip_prefix('{')?;
    // Find the end of the first key — `:`, `,` or `}`.
    let end = inner
        .find([':', ',', '}'])
        .unwrap_or(inner.len());
    let key = inner[..end].trim();
    if key.is_empty() {
        return None;
    }
    // List? Only if the key is followed by `: [`.
    let rest = inner.get(end..).unwrap_or("").trim_start();
    let is_list = rest
        .strip_prefix(':')
        .map(|r| r.trim_start().starts_with('['))
        .unwrap_or(false);
    Some((key, is_list))
}

fn ts_safe_name(name: &str) -> &str {
    // The arg-name → JS-identifier policy. Op-local names today are all
    // bare ASCII; this keeps the door open for future names with hyphens.
    name
}

fn quote_ts(s: &str) -> String {
    let escaped = s
        .replace('\\', "\\\\")
        .replace('\'', "\\'");
    format!("'{escaped}'")
}

const PRELUDE: &str = r#"/**
 * The runtime handle returned by every `ship.<domain>.<op>(...)` call.
 * Backed by the daemon's SSE patch protocol — see
 * `packages/ship-set-runtime/src/data.ts` for the canonical implementation
 * used by the `.set` compiler. TS-only consumers can import a runtime
 * implementation from `@ship/sdk/data` once it lands (phase 2).
 */
export interface DataHandle<T> {
  /** Latest value, or null until the first SSE patch arrives. */
  (): T | null;
  /** Subscribe to value changes. Returns an unsubscribe function. */
  subscribe(fn: (value: T | null) => void): () => void;
  /** Tear down the SSE subscription. */
  dispose(): void;
}
"#;

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn emits_path_union_for_known_op() {
        let out = emit().expect("emit succeeds");
        assert!(out.contains("'agents.summaries'"), "missing path entry");
        assert!(
            out.contains("summaries(): DataHandle<AgentsSummariesResponse>;"),
            "migrated agents.summaries should be typed, not unknown",
        );
        assert!(out.contains("export const SHIP_OPS_META"), "missing ops meta export");
    }

    #[test]
    fn migrated_agents_ops_are_typed_not_unknown() {
        let out = emit().expect("emit succeeds");
        // Slice out the `agents: { ... };` block and assert it carries no
        // `DataHandle<unknown>` — the load-bearing data.ts gate for a migrated
        // domain (criterion: zero unknown handles for migrated domains).
        let start = out.find("  agents: {").expect("agents block present");
        let block = &out[start..];
        let end = block.find("\n  };").expect("agents block closes");
        let block = &block[..end];
        assert!(
            !block.contains("DataHandle<unknown>"),
            "agents block still has an untyped handle:\n{block}",
        );
        assert!(block.contains("detail(args: { id: string; }): DataHandle<AgentDetail>;"));
        assert!(block.contains("list(): DataHandle<AgentIndexResponse>;"));
    }

    #[test]
    fn emits_type_imports_for_migrated_returns() {
        let out = emit().expect("emit succeeds");
        assert!(out.contains("from '../generated';"), "missing type import block");
        assert!(out.contains("  AgentDetail,"), "missing AgentDetail import");
        assert!(out.contains("  AgentsSummariesResponse,"), "missing summaries import");
    }

    #[test]
    fn emits_required_arg_with_explicit_type() {
        let out = emit().expect("emit succeeds");
        // `agents.detail` takes `id: string` (required).
        assert!(out.contains("detail(args: { id: string; })"), "expected required-arg signature");
    }

    #[test]
    fn emits_optional_args_with_optional_arg_object() {
        let out = emit().expect("emit succeeds");
        // `chat.state` takes only optional args; the `args` parameter itself should be optional.
        assert!(out.contains("state(args?: { workspace_id?: string; })"), "expected all-optional shape");
    }

    #[test]
    fn emits_example_block_per_op() {
        let out = emit().expect("emit succeeds");
        // Every op should have an @example block. Count handles by the method
        // signature shape (`): DataHandle<`), which is type-agnostic now that
        // migrated ops resolve to named types instead of `unknown`.
        let example_count = out.matches("@example").count();
        let signature_count = out.matches("): DataHandle<").count();
        assert_eq!(
            example_count, signature_count,
            "every op signature should carry an @example block; got {example_count} examples for {signature_count} ops",
        );
    }

    #[test]
    fn example_uses_set_declaration_and_template() {
        let out = emit().expect("emit succeeds");
        // `data agents = ship.agents.summaries()` declaration is still emitted.
        assert!(
            out.contains("data agents = ship.agents.summaries()"),
            "missing .set declaration in @example",
        );
        // Every op now returns a named type, so the template-usage heuristic
        // renders the guarded read pattern (JSON.stringify of the bound signal)
        // rather than the inline-shape for-loop.
        assert!(
            out.contains("JSON.stringify(agents(), null, 2)"),
            "missing named-type usage in @example",
        );
    }

    #[test]
    fn example_required_args_get_placeholder_literals() {
        let out = emit().expect("emit succeeds");
        // `agents.detail` requires `id: string`; example should pass a literal.
        assert!(
            out.contains("data agents = ship.agents.detail({ id: 'id' })"),
            "expected placeholder for required string arg",
        );
    }
}
