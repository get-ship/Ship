#![allow(clippy::if_same_then_else)]
//! `.d.ts` declaration file emitter.
//!
//! Walks `<state>`, `<data>`, `<prop>`, and `<use-* as=>` declarations
//! from the IR and emits a TypeScript declaration file that authors can
//! import as `Scope`.

use crate::ir::{AttrInstr, DataDecl, ElementInstr, Instr, Program, PropDecl, PropKind, StateDecl};

/// Emit the `.sui.d.ts` text for a compiled `.sui` file.
pub fn emit_dts(program: &Program) -> String {
    let mut members: Vec<(String, String)> = Vec::new();

    for s in &program.state {
        members.push((s.name.clone(), state_ts_type(s)));
    }
    for d in &program.data {
        members.push((d.name.clone(), data_ts_type(d)));
    }
    for p in &program.props {
        // Prop names in templates are kebab-case to match HTML attribute
        // convention (e.g. `<prop name="font-size">`); the runtime
        // camelCases them to JS identifiers (`fontSize`) via
        // ui-runtime/component-factory.ts::camelOf. Scope must agree —
        // emit the camelCased identifier so `state.fontSize` typechecks.
        members.push((super::util::camel_of(&p.name), prop_ts_type(p)));
    }
    collect_use_bindings(&program.template, &mut members);
    collect_ref_bindings(&program.template, &mut members);

    if members.is_empty() {
        return "// generated by sui-compiler — no scope declarations\nexport interface Scope {}\n"
            .to_string();
    }

    let needs_live_state = members.iter().any(|(_, t)| t.contains("LiveState"));
    let import_line = if needs_live_state {
        "import type { Signal, LiveState } from '@ship/ui-runtime'\n"
    } else {
        "import type { Signal } from '@ship/ui-runtime'\n"
    };

    let mut out = String::with_capacity(256);
    out.push_str("// generated by sui-compiler — DO NOT EDIT\n");
    out.push_str(import_line);
    out.push('\n');
    out.push_str("export interface Scope {\n");
    for (name, ty) in &members {
        out.push_str(&format!("  {name}: {ty}\n"));
    }
    out.push_str("}\n");
    out
}

fn state_ts_type(s: &StateDecl) -> String {
    format!("Signal<{}>", infer_ts_type(&s.value.source))
}

fn data_ts_type(d: &DataDecl) -> String {
    if d.live {
        "Signal<LiveState<unknown>>".to_string()
    } else {
        "Signal<unknown>".to_string()
    }
}

fn prop_ts_type(p: &PropDecl) -> String {
    let inner = match &p.kind {
        PropKind::String => "string".to_string(),
        PropKind::Bool => "boolean".to_string(),
        PropKind::Number => "number".to_string(),
        PropKind::Union(values) => values
            .iter()
            .map(|v| format!("'{v}'"))
            .collect::<Vec<_>>()
            .join(" | "),
    };
    format!("Signal<{inner}>")
}

/// Infer a TypeScript primitive type from a JS literal expression.
fn infer_ts_type(src: &str) -> &str {
    let s = src.trim();
    if is_number_literal(s) {
        return "number";
    }
    if is_string_literal(s) {
        return "string";
    }
    if s == "true" || s == "false" {
        return "boolean";
    }
    if is_array_literal(s) {
        return "unknown[]";
    }
    "unknown"
}

fn is_number_literal(s: &str) -> bool {
    if s.is_empty() {
        return false;
    }
    let s = s.strip_prefix('-').unwrap_or(s);
    s.chars().all(|c| c.is_ascii_digit() || c == '.' || c == '_')
        && s.chars().any(|c| c.is_ascii_digit())
}

fn is_string_literal(s: &str) -> bool {
    (s.starts_with('\'') && s.ends_with('\'') && s.len() >= 2)
        || (s.starts_with('"') && s.ends_with('"') && s.len() >= 2)
        || (s.starts_with('`') && s.ends_with('`') && s.len() >= 2)
}

fn is_array_literal(s: &str) -> bool {
    s.starts_with('[') || s == "[]"
}

/// Walk template instructions and collect `bind:this={var}` refs.
/// Each ref contributes `var: Signal<T | null>` where `T` is inferred
/// from the parent element's tag — `HTMLElementTagNameMap` for known
/// built-ins, `HTMLElement` for everything else (custom elements,
/// unknown tags).
fn collect_ref_bindings(instrs: &[Instr], out: &mut Vec<(String, String)>) {
    for instr in instrs {
        match instr {
            Instr::Element(el) => {
                walk_element_for_refs(el, out);
            }
            Instr::If(if_instr) => {
                for b in &if_instr.branches {
                    collect_ref_bindings(&b.body, out);
                }
                if let Some(eb) = &if_instr.else_body {
                    collect_ref_bindings(eb, out);
                }
            }
            Instr::For(f) => {
                collect_ref_bindings(&f.body, out);
                if let Some(eb) = &f.else_body {
                    collect_ref_bindings(eb, out);
                }
            }
            Instr::Match(m) => {
                for c in &m.cases {
                    collect_ref_bindings(&c.body, out);
                }
                if let Some(d) = &m.default {
                    collect_ref_bindings(d, out);
                }
            }
            Instr::WhileLoading(wl) => collect_ref_bindings(&wl.body, out),
            Instr::WhileError(we) => collect_ref_bindings(&we.body, out),
            _ => {}
        }
    }
}

fn walk_element_for_refs(el: &ElementInstr, out: &mut Vec<(String, String)>) {
    for attr in &el.attrs {
        if let AttrInstr::BindThis { var, .. } = attr {
            let element_ts = element_type_for_tag(&el.tag);
            out.push((var.clone(), format!("Signal<{element_ts} | null>")));
        }
    }
    collect_ref_bindings(&el.children, out);
}

/// Map an HTML tag to its `HTMLElementTagNameMap` interface name.
/// Custom elements (containing `-`) and unknown tags fall through to
/// `HTMLElement`. The set covers the tags an author plausibly hangs
/// `bind:this` on; expand as the surface grows.
fn element_type_for_tag(tag: &str) -> &'static str {
    let lower = tag.to_ascii_lowercase();
    if lower.contains('-') {
        return "HTMLElement";
    }
    match lower.as_str() {
        "a" => "HTMLAnchorElement",
        "area" => "HTMLAreaElement",
        "audio" => "HTMLAudioElement",
        "br" => "HTMLBRElement",
        "base" => "HTMLBaseElement",
        "body" => "HTMLBodyElement",
        "button" => "HTMLButtonElement",
        "canvas" => "HTMLCanvasElement",
        "data" => "HTMLDataElement",
        "datalist" => "HTMLDataListElement",
        "details" => "HTMLDetailsElement",
        "dialog" => "HTMLDialogElement",
        "div" => "HTMLDivElement",
        "dl" => "HTMLDListElement",
        "embed" => "HTMLEmbedElement",
        "fieldset" => "HTMLFieldSetElement",
        "form" => "HTMLFormElement",
        "h1" | "h2" | "h3" | "h4" | "h5" | "h6" => "HTMLHeadingElement",
        "head" => "HTMLHeadElement",
        "hr" => "HTMLHRElement",
        "html" => "HTMLHtmlElement",
        "iframe" => "HTMLIFrameElement",
        "img" => "HTMLImageElement",
        "input" => "HTMLInputElement",
        "label" => "HTMLLabelElement",
        "legend" => "HTMLLegendElement",
        "li" => "HTMLLIElement",
        "link" => "HTMLLinkElement",
        "map" => "HTMLMapElement",
        "menu" => "HTMLMenuElement",
        "meta" => "HTMLMetaElement",
        "meter" => "HTMLMeterElement",
        "object" => "HTMLObjectElement",
        "ol" => "HTMLOListElement",
        "optgroup" => "HTMLOptGroupElement",
        "option" => "HTMLOptionElement",
        "output" => "HTMLOutputElement",
        "p" => "HTMLParagraphElement",
        "picture" => "HTMLPictureElement",
        "pre" => "HTMLPreElement",
        "progress" => "HTMLProgressElement",
        "q" => "HTMLQuoteElement",
        "script" => "HTMLScriptElement",
        "select" => "HTMLSelectElement",
        "slot" => "HTMLSlotElement",
        "source" => "HTMLSourceElement",
        "span" => "HTMLSpanElement",
        "style" => "HTMLStyleElement",
        "table" => "HTMLTableElement",
        "tbody" | "tfoot" | "thead" => "HTMLTableSectionElement",
        "td" | "th" => "HTMLTableCellElement",
        "template" => "HTMLTemplateElement",
        "textarea" => "HTMLTextAreaElement",
        "time" => "HTMLTimeElement",
        "title" => "HTMLTitleElement",
        "tr" => "HTMLTableRowElement",
        "track" => "HTMLTrackElement",
        "ul" => "HTMLUListElement",
        "video" => "HTMLVideoElement",
        _ => "HTMLElement",
    }
}

/// Walk template instructions and collect `<use-X as="Y">` bindings.
fn collect_use_bindings(instrs: &[Instr], out: &mut Vec<(String, String)>) {
    for instr in instrs {
        if let Instr::Element(el) = instr {
            if let Some(hook_name) = el.tag.strip_prefix("use-") {
                // Look for an `as=` attribute that binds the hook under an alias.
                for attr in &el.attrs {
                    if let crate::ir::AttrInstr::Static { name, value, .. } = attr
                        && name == "as" && !value.is_empty() {
                            let camel = to_camel(hook_name);
                            out.push((
                                value.clone(),
                                format!("ReturnType<typeof use{camel}>"),
                            ));
                        }
                }
            }
            collect_use_bindings(&el.children, out);
        }
    }
}

fn to_camel(kebab: &str) -> String {
    kebab
        .split('-')
        .enumerate()
        .map(|(i, part)| {
            if i == 0 {
                let mut c = part.chars();
                match c.next() {
                    None => String::new(),
                    Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                }
            } else {
                let mut c = part.chars();
                match c.next() {
                    None => String::new(),
                    Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
                }
            }
        })
        .collect()
}
