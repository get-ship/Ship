use super::super::writer::{js_string, Writer};
use crate::lower::Lowered;
use crate::CompileOpts;

pub(super) fn emit_imports(w: &mut Writer, lowered: &Lowered, opts: &CompileOpts) {
    let is_shadow = opts.component_meta.as_ref().map(|m| m.shadow).unwrap_or(false);
    let mut imports: Vec<String> = lowered.runtime_imports.iter().map(|s| s.to_string()).collect();
    if is_shadow {
        let sym = "adoptSuiSheets".to_string();
        if !imports.contains(&sym) {
            imports.push(sym);
            imports.sort();
        }
    }
    // Built-in transition factories are auto-imported when the template
    // references them — authors don't have to wire fade/slide/scale by
    // hand. Custom transition names (anything not in this set) still
    // resolve through `$scope` (i.e. the controller's scope: factory).
    for &name in &lowered.transition_builtins {
        let s = name.to_string();
        if !imports.contains(&s) {
            imports.push(s);
        }
    }
    imports.sort();
    w.line("// AUTO-GENERATED by sui-compiler. Do not edit.");
    if imports.is_empty() {
        w.line("import \"@ship/sui-runtime\";");
    } else {
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-runtime\";",
            imports.join(", ")
        ));
    }
    if !lowered.dom_imports.is_empty() {
        let dom: Vec<String> = lowered.dom_imports.iter().map(|s| s.to_string()).collect();
        w.line(&format!(
            "import {{ {} }} from \"@ship/sui-dom\";",
            dom.join(", ")
        ));
    }
    if lowered.uses_template_hooks {
        w.line("import \"@ship/sui-runtime/template-hooks\";");
    }
    if lowered.uses_route {
        w.line("import { route as __routeFactory } from \"@ship/sui-runtime/route\";");
    }
    if let Some(setup) = &opts.setup_url {
        w.line(&format!("import setup from {};", js_string(setup)));
    }
    w.nl();
}
