// /component-viewer/[name] — controller for the component viewer route.
// Reads the [name] segment from the route params and exposes it as a
// derived signal so the template can render the right component. Calls
// `ship.ui.packs` + `ship.ui.read` to fetch the catalog + source the
// studio's "show source" panel renders.

import { controller, derived, signal, type ReadonlySignal } from '@ship/sui-runtime'
import type { ViewScope } from '@ship/sui-runtime'
import type { Scope } from './page.sui'
import { ops } from '../../../../src/ops'

export type ViewerComponent = {
  tag: string
  file: string
  title: string
}

export type ViewerPack = {
  id: string
  category: string
  title: string
  components: ViewerComponent[]
}

export default controller<Scope>({
  scope: (_opts: ViewScope<Scope>, _host) => {
    // The [name] segment is captured by the runtime's `route.params.name()`
    // (set up by `defineRoutes` from the LAYOUTS / DYNAMIC_ROUTE_PATTERNS
    // table generated by `/home/madvib/dev/sui//home/madvib/dev/sui/crates/deck/deck-bundler/src/routes.rs`).
    const name = derived(() => _opts.route?.params?.name?.() ?? '')

    // Find the matching component from `ship.ui.packs` for this name.
    // The catalog is the source of truth for which pack the component
    // belongs to + its on-disk source path (`file`).
    const pack: ReadonlySignal<ViewerPack | null> = signal<ViewerPack | null>(null)
    const source: ReadonlySignal<string> = signal<string>('')
    const loadError: ReadonlySignal<string> = signal<string>('')

    // Re-run when the route's [name] changes.
    derived(async () => {
      const n = name()
      if (!n) return
      loadError('')
      source('')
      pack(null)
      try {
        // Packs returns the flat catalog; pick the component matching
        // `tag === n`. Future: filter by category to scope the search
        // (the viewer shows any component across @sui + @ship + @user).
        const resp = await ops.ui.packs({})
        const found: ViewerComponent | undefined = resp.packs
          .flatMap((p) => p.components)
          .find((c) => c.tag === n)
        if (!found) {
          loadError(`component "${n}" not found in any pack`)
          return
        }
        // Build a minimal ViewerPack so the template can show the source
        // path (title / category is upstream — kept simple for the
        // first slice; the studio at /studio/components/[name] owns
        // the rich catalog-driven surface).
        pack({
          id: '',
          category: '',
          title: '',
          components: [found],
        })
        // Read the source via the same RPC. The handler resolves
        // `<ship_dir>/.deck/sources/<file>` and returns the raw text.
        const r = await ops.ui.read({ path: found.file })
        source(r.source)
      } catch (e) {
        loadError((e as Error).message ?? String(e))
      }
    }) // fire-and-forget — the signals update on resolution.

    return { name, pack, source, loadError }
  },
})
