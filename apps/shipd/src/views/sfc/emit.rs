//! JS code emission for `.ship` components.
//!
//! Produces a self-contained ES module string per component. The module
//! defines a `class ShipComponent extends HTMLElement` and calls
//! `customElements.define(TAG, ShipComponent)`. Loaded lazily (once per
//! tag) by the host page via `<script type="module" src="/_ship/components/<tag>.js">`.
//!
//! Runtime contract (what the wrapper provides to the user script):
//! - `props`        — read-only object of decoded attribute values (with defaults).
//! - `signal(init)` — returns `{ get(), set(v) }`. The wrapper pre-knows
//!                    the signal-name list (from compile-time schema
//!                    extraction) and assigns names by call order, so
//!                    `const $foo = signal(0)` becomes the namespaced
//!                    key `_<tag>_<inst>_foo` automatically.
//! - `effect(deps, fn)` — subscribe `fn` to changes on one or more signal
//!                        handles. Runs once eagerly.
//! - `emit(name, payload)` — `dispatchEvent(new CustomEvent(name, ...))`
//!                            with `bubbles: true`.
//! - `onConnect(fn)` / `onDisconnect(fn)` — register lifecycle hooks.
//!
//! Signal storage is bridged into Datastar's signal store. For each
//! declared signal, the wrapper writes `data-signals:<scoped_key>` on
//! the host element with the JSON-encoded initial value; Datastar's
//! `signals` plugin (data-* MutationObserver) ingests the attribute
//! and creates the reactive signal. Programmatic `.set(v)` re-writes
//! the same attribute, which Datastar re-applies. The wrapper listens
//! to the `datastar-signal-patch` event on `document` to keep a local
//! cache for `.get()` and to fan out changes to `effect(...)`
//! subscribers. `window.__ShipSignals` is kept as a debug mirror only.
//!
//! Helper functions (attribute-name conversion, prop-decoder
//! generation, JS template-literal escaping) live in
//! [`super::emit_helpers`].

use super::emit_helpers::{build_prop_decoders, escape_template_literal, to_attr_name};
use super::script::ScriptSchema;

/// Inputs to JS emission, fully composed by `mod.rs`.
pub struct EmitInputs<'a> {
    pub tag: &'a str,
    pub schema: &'a ScriptSchema,
    pub user_script: &'a str,
    /// Already-rendered template HTML with `__SHIP_INST__` placeholders
    /// in place of per-instance signal-name segments.
    pub rendered_html: &'a str,
    /// Already-scoped CSS, or the original CSS for `<style global>` blocks.
    pub scoped_css: &'a str,
}

/// Emit the JS module string for this component.
pub fn emit(inputs: &EmitInputs<'_>) -> String {
    let prop_names_js = inputs
        .schema
        .props
        .iter()
        .map(|p| format!("\"{}\"", to_attr_name(&p.name)))
        .collect::<Vec<_>>()
        .join(", ");
    // Camel-case prop names — used to look up props on the decoded
    // object and to match attributeChangedCallback names back to signals.
    let prop_names_camel_js = inputs
        .schema
        .props
        .iter()
        .map(|p| format!("\"{}\"", p.name))
        .collect::<Vec<_>>()
        .join(", ");
    let signal_names_js = inputs
        .schema
        .signals
        .iter()
        .map(|s| format!("\"{s}\""))
        .collect::<Vec<_>>()
        .join(", ");
    let prop_decoders = build_prop_decoders(&inputs.schema.props);
    let template_literal = escape_template_literal(inputs.rendered_html);
    let style_literal = escape_template_literal(inputs.scoped_css);

    format!(
        r#"// Auto-generated by Ship SFC compiler — do not edit.
(function() {{
  const TAG = "{tag}";
  const TEMPLATE = `{template_literal}`;
  const STYLE = `{style_literal}`;
  const PROP_NAMES = [{prop_names_js}];
  // Camel-case prop names — used to seed per-instance signals and to
  // route attributeChangedCallback updates back to the matching signal.
  const PROP_NAMES_CAMEL = [{prop_names_camel_js}];
  const SIGNAL_NAMES = [{signal_names_js}];
  let __seq = 0;
  let __styleInjected = false;

  if (!window.__ShipSignals) window.__ShipSignals = {{}};

  class ShipComponent extends HTMLElement {{
    static get observedAttributes() {{ return PROP_NAMES; }}
    constructor() {{
      super();
      this.__inst = ++__seq;
      this.__hooks = {{ connect: [], disconnect: [] }};
      this.__signals = {{}};
      this.__effects = [];
      this.__patchListener = null;
    }}
    connectedCallback() {{
      if (!__styleInjected && STYLE) {{
        const s = document.createElement("style");
        s.setAttribute("data-ship-component", TAG);
        s.textContent = STYLE;
        document.head.appendChild(s);
        __styleInjected = true;
      }}
      this.setAttribute("data-component", TAG);
      this.__patchListener = (e) => this.__onSignalPatch(e);
      document.addEventListener("datastar-signal-patch", this.__patchListener);
      const props = this.__readProps();
      this.__bootstrap(props);
      const html = TEMPLATE.replaceAll("__SHIP_INST__", String(this.__inst));
      this.innerHTML = html;
      this.__wireDataFor();
      for (const fn of this.__hooks.connect) {{
        try {{ fn(this); }} catch (e) {{ console.error("[ship:" + TAG + "] onConnect error:", e); }}
      }}
    }}
    attributeChangedCallback(attrName, _old, newValue) {{
      // When a host attribute changes after mount, sync the matching
      // prop signal so templates and effects react. The attribute name
      // is kebab-case; the __signals map keys are lowercased
      // camelCase. Strip dashes (`fetch-url` → `fetchurl`) for the
      // lookup — matches __makeSignal's `.toLowerCase()` storage.
      const key = attrName.replace(/-/g, "");
      const sig = this.__signals[key];
      if (sig && typeof sig.set === "function") sig.set(newValue);
    }}
    disconnectedCallback() {{
      if (this.__patchListener) {{
        document.removeEventListener("datastar-signal-patch", this.__patchListener);
        this.__patchListener = null;
      }}
      for (const fn of this.__hooks.disconnect) {{
        try {{ fn(this); }} catch (e) {{ console.error("[ship:" + TAG + "] onDisconnect error:", e); }}
      }}
    }}
    __readProps() {{
{prop_decoders}
      return props;
    }}
    /// Wire `<template data-for="X in expr" data-key="K">…</template>`
    /// elements after innerHTML is set. Datastar v1.0.0-RC.7 has no
    /// for/each plugin; the SFC framework owns iteration. Each
    /// template is replaced by an anchor `<!--ship-for-->` comment
    /// plus a sibling fragment that re-renders whenever the iterated
    /// expression's signal dependencies change.
    ///
    /// Reactivity model: the expression is parsed for signal
    /// references (`$_<tag>_<inst>_<name>`); the renderer subscribes
    /// to each via __subscribe(). Item references (`a.id`,
    /// `(item, i) in $list` → `item.id`) are resolved via
    /// `new Function` evaluation at render time, with the array
    /// element bound as the `item` (or named) variable.
    ///
    /// Item-scoped Datastar reactivity is intentionally NOT supported:
    /// references inside an iterated child to its own item are baked
    /// at render time, not re-bound on item update. The whole iteration
    /// re-runs when the array signal changes — replace the array, not
    /// individual items.
    __wireDataFor() {{
      const host = this;
      const templates = Array.from(host.querySelectorAll("template[data-for]"));
      for (const tmpl of templates) {{
        const expr = tmpl.getAttribute("data-for") || "";
        const m = expr.match(/^\s*(\([^)]+\)|\w+)\s+in\s+(.+)$/);
        if (!m) continue;
        const bindRaw = m[1].replace(/[()\s]/g, "").split(",");
        const itemName = bindRaw[0] || "item";
        const indexName = bindRaw[1] || "__i";
        const arrayExpr = m[2];

        // The compiler has rewritten user signal references in attribute
        // values to `$_<safe_tag>_<inst>_<name>`. Strip that prefix to
        // recover the user-declared name we use to look up handles in
        // `__signals`. Anything that doesn't match the prefix is left
        // alone (e.g. `$item.foo` in nested cases — handled by bake).
        const safeTag = TAG.replace(/-/g, "_");
        const prefix = "_" + safeTag + "_" + host.__inst + "_";
        const sigRefs = [];
        for (const m2 of arrayExpr.matchAll(/\$([A-Za-z_][\w]*)/g)) {{
          const ref = m2[1];
          if (ref.indexOf(prefix) === 0) {{
            sigRefs.push(ref.slice(prefix.length));
          }} else {{
            sigRefs.push(ref);
          }}
        }}

        // Replace the template with a placeholder comment we'll append
        // siblings AFTER. Keep the template element to clone from.
        const anchor = document.createComment("ship-for");
        tmpl.parentNode.insertBefore(anchor, tmpl);
        tmpl.remove();

        const innerHtml = (() => {{
          // Concat the children of the <template> into a string. We
          // cloneNode children but going via outerHTML means we re-
          // process the element via DOMParser at render time, which
          // gives us a fresh subtree per item without sharing event
          // listeners.
          const tpl = document.createElement("div");
          for (const c of tmpl.content.childNodes) tpl.appendChild(c.cloneNode(true));
          return tpl.innerHTML;
        }})();

        let renderedNodes = [];
        const sigStore = host.__signals;
        function evalArray() {{
          // Replace `$<scoped-name>` refs with reads from the user-named
          // signal cache. Strips the `<safe_tag>_<inst>_` prefix to
          // recover the user-declared signal name on this host.
          const body = arrayExpr.replace(/\$([A-Za-z_][\w]*)/g, (_, n) => {{
            const userName = n.indexOf(prefix) === 0 ? n.slice(prefix.length) : n;
            return `(__store[${{JSON.stringify(userName)}}] && __store[${{JSON.stringify(userName)}}].__cache)`;
          }});
          try {{
            return new Function("__store", "return (" + body + ");")(sigStore) || [];
          }} catch (e) {{
            console.error("[ship-for] eval failed:", arrayExpr, e);
            return [];
          }}
        }}
        function lookupItem(item, path) {{
          if (!path) return item;
          const parts = path.split(".");
          let v = item;
          for (const p of parts) {{ if (v == null) break; v = v[p]; }}
          return v;
        }}
        function evalItemExpr(expr, item, index) {{
          // Evaluate a JS expression in a scope where `<itemName>` is
          // bound to `item` and `<indexName>` is `index`. Used to
          // resolve attribute values + text content at iteration time
          // — no Datastar reactivity inside iterated children, which
          // is the documented data-for contract (snapshot per render).
          try {{
            return new Function(itemName, indexName, "return (" + expr + ");")(item, index);
          }} catch (e) {{
            console.warn("[ship-for] item expr failed:", expr, e);
            return "";
          }}
        }}
        function bakeNode(node, item, index) {{
          if (node.nodeType === 3) return; // text — leave alone
          if (node.nodeType !== 1) return;
          const el = node;
          // Resolve data-attr:NAME → NAME, data-text → textContent,
          // data-class:NAME → toggleClass, data-show → display.
          // Walk attributes once and collect actions; mutate after.
          const toRemove = [];
          for (const a of Array.from(el.attributes)) {{
            const n = a.name, v = a.value;
            if (n.startsWith("data-attr:")) {{
              const target = n.slice("data-attr:".length);
              const result = evalItemExpr(v, item, index);
              if (result === false || result == null) el.removeAttribute(target);
              else el.setAttribute(target, result === true ? "" : String(result));
              toRemove.push(n);
            }} else if (n === "data-text") {{
              el.textContent = String(evalItemExpr(v, item, index) ?? "");
              toRemove.push(n);
            }} else if (n.startsWith("data-class:")) {{
              const cls = n.slice("data-class:".length);
              if (evalItemExpr(v, item, index)) el.classList.add(cls);
              else el.classList.remove(cls);
              toRemove.push(n);
            }} else if (n === "data-show") {{
              if (!evalItemExpr(v, item, index)) el.style.display = "none";
              toRemove.push(n);
            }}
          }}
          for (const n of toRemove) el.removeAttribute(n);
          for (const child of Array.from(el.childNodes)) bakeNode(child, item, index);
        }}
        function render() {{
          for (const n of renderedNodes) n.remove();
          renderedNodes = [];
          const arr = evalArray();
          if (!Array.isArray(arr)) return;
          arr.forEach((item, i) => {{
            const tpl = document.createElement("template");
            tpl.innerHTML = innerHtml;
            const frag = tpl.content;
            // Walk the cloned subtree resolving data-* attributes
            // against the per-item scope, then insert into the
            // parent right after the anchor.
            for (const child of Array.from(frag.childNodes)) bakeNode(child, item, i);
            const nodes = Array.from(frag.childNodes);
            for (const n of nodes) {{
              anchor.parentNode.insertBefore(n, anchor.nextSibling);
            }}
            renderedNodes.push(...nodes);
          }});
        }}

        // Subscribe to each referenced signal so updates re-render.
        for (const name of sigRefs) {{
          const s = sigStore[name];
          if (s && typeof s.__subscribe === "function") s.__subscribe(render);
        }}
        render();
      }}
    }}

    __sigKey(name) {{
      // Lowercase the entire key so it survives HTML's attribute-name
      // case-folding (data-* attribute NAMES are stored lowercase by
      // every HTML parser; if we keep camelCase here, the storage key
      // mismatches the rewritten reference in attribute VALUES, which
      // preserve case). Signal names with collisions after lowercase
      // are reported as a script-block error at compile time —
      // see script.rs::extract_signals.
      return ("_" + TAG.replace(/-/g, "_") + "_" + this.__inst + "_" + name).toLowerCase();
    }}
    __onSignalPatch(e) {{
      const detail = e && e.detail;
      if (!detail) return;
      for (const name in this.__signals) {{
        const handle = this.__signals[name];
        if (handle && handle.__key in detail) {{
          const v = detail[handle.__key];
          if (handle.__cache !== v) {{
            handle.__cache = v;
            for (const fn of handle.__subs) {{
              try {{ fn(); }} catch (err) {{ console.error("[ship:" + TAG + "] effect error:", err); }}
            }}
          }}
        }}
      }}
    }}
    __writeDsSignal(key, value) {{
      this.setAttribute("data-signals:" + key, JSON.stringify(value));
    }}
    __makeSignal(name, initial) {{
      const key = this.__sigKey(name);
      const host = this;
      window.__ShipSignals[key] = initial;
      host.__writeDsSignal(key, initial);
      const subs = new Set();
      const handle = {{
        __key: key,
        __cache: initial,
        __subs: subs,
        get() {{ return handle.__cache; }},
        set(v) {{
          if (handle.__cache === v) return;
          handle.__cache = v;
          window.__ShipSignals[key] = v;
          host.__writeDsSignal(key, v);
          for (const fn of subs) {{ try {{ fn(); }} catch (e) {{ console.error(e); }} }}
        }},
        __subscribe(fn) {{ subs.add(fn); return () => subs.delete(fn); }},
      }};
      // Lowercase the map key to match the __sigKey lowercasing —
      // both attribute storage and __wireDataFor lookups are
      // case-insensitive in resolution.
      this.__signals[name.toLowerCase()] = handle;
      return handle;
    }}
    __bootstrap(props) {{
      const host = this;
      // Auto-seed a per-instance signal for every declared prop so
      // templates can reference `$<propName>` directly and stay reactive
      // when attributes change. Prop signals share the same scoped key
      // namespace as user-declared signals.
      for (const name of PROP_NAMES_CAMEL) {{
        host.__makeSignal(name, props[name]);
      }}
      const onConnect = (fn) => host.__hooks.connect.push(fn);
      const onDisconnect = (fn) => host.__hooks.disconnect.push(fn);
      // composed: true so the event crosses shadow-DOM boundaries when
      // the component is consumed inside a shadow root. bubbles: true so
      // ancestor listeners (and Datastar's data-on:* attribute hooks) fire.
      const emit = (name, payload) => host.dispatchEvent(
        new CustomEvent(name, {{ detail: payload, bubbles: true, composed: true }})
      );
      let __signalIdx = 0;
      const signal = (initial) => {{
        const name = SIGNAL_NAMES[__signalIdx++];
        if (!name) {{
          console.warn("[ship:" + TAG + "] signal() called more times than schema declared");
          return host.__makeSignal("__anon" + __signalIdx, initial);
        }}
        return host.__makeSignal(name, initial);
      }};
      const effect = (deps, fn) => {{
        const handles = Array.isArray(deps) ? deps : [deps];
        const run = () => {{ try {{ fn(); }} catch (e) {{ console.error(e); }} }};
        for (const h of handles) {{
          if (h && typeof h.__subscribe === "function") h.__subscribe(run);
        }}
        run();
      }};
      // reflectAttr(name, sig) — keep a host attribute in sync with a
      // signal value. Useful for state that needs to reach CSS hooks
      // or external observers without going through inline styles.
      const reflectAttr = (name, sig) => {{
        if (!sig || typeof sig.__subscribe !== "function") return;
        const apply = () => {{
          const v = sig.get();
          if (v == null || v === false) host.removeAttribute(name);
          else host.setAttribute(name, v === true ? "" : String(v));
        }};
        sig.__subscribe(apply);
        apply();
      }};
      // data(fn) — async signal sourcing for mount-time fetches. Same
      // shape as signal(): consumes one SIGNAL_NAMES slot in declaration
      // order. The signal initializes to null, then resolves to fn()'s
      // return value. fn receives `{{ signal }}` (an AbortSignal) so
      // authors can wire it into fetch() and the in-flight request
      // cancels on disconnect.
      const data = (fn) => {{
        const name = SIGNAL_NAMES[__signalIdx++];
        const sig = host.__makeSignal(name || ("__data" + __signalIdx), null);
        const ac = new AbortController();
        host.__hooks.disconnect.push(() => ac.abort());
        Promise.resolve()
          .then(() => fn({{ signal: ac.signal }}))
          .then((v) => {{ if (!ac.signal.aborted) sig.set(v); }})
          .catch((e) => {{
            if (!ac.signal.aborted) {{
              console.error("[ship:" + TAG + "] data() error:", e);
              host.dispatchEvent(new CustomEvent("data-error", {{
                detail: {{ name: name, error: e }}, bubbles: true, composed: true
              }}));
            }}
          }});
        return sig;
      }};
      try {{
        // ---- begin user script ----
{user_script}
        // ---- end user script ----
      }} catch (e) {{
        console.error("[ship:" + TAG + "] script error:", e);
      }}
      return {{}};
    }}
  }}

  if (!customElements.get(TAG)) {{
    customElements.define(TAG, ShipComponent);
  }}
}})();
"#,
        tag = inputs.tag,
        template_literal = template_literal,
        style_literal = style_literal,
        prop_names_js = prop_names_js,
        signal_names_js = signal_names_js,
        prop_decoders = prop_decoders,
        user_script = inputs.user_script,
    )
}

