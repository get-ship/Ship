#![allow(clippy::doc_overindented_list_items)]
//! `ship.*` op catalog — the single source of truth for what view
//! templates (`ship.<domain>.<op>`), `window.ship.*` codegen, and MCP
//! tool auto-registration all read.
//!
//! Served at `GET /api/v1/ship/schema`. Each op carries enough metadata
//! for lint, autocomplete, and permission mapping:
//!
//! - `name`         — dotted op path (e.g. `agents.detail`).
//! - `description`  — one-line human summary.
//! - `args`         — list of argument descriptors with kwarg name + kind.
//! - `returns`      — string tag naming the return shape.
//! - `permission`   — capability required to call. Metadata-only today;
//!                    enforcement lands with the caller-identity model.
//! - `sensitive`    — flag that lint / UI can warn on (payloads may
//!                    contain secrets, git content, etc.).
//!
//! Arg / return kinds are string tags today — keeps the surface light
//! (no JSON schema per op). Autocomplete + MCP tool bindings only need
//! name-shape matching; full schemas land when there's a concrete need.

use std::sync::LazyLock;

use axum::Json;
use serde::Serialize;

use crate::wire::MeshResponse;

/// `GET /api/v1/ship/schema` — catalog of every `ship.<domain>.<op>` the
/// registry exposes. Consumers:
/// - `@ship/shell` TS SDK: codegen typed `window.ship.*` methods
/// - Lint: flag template calls that don't match a known op
/// - MCP server: auto-register ops as tools
/// - Third-party view authors: editor autocomplete via `/api/v1/ship/schema`
#[utoipa::path(
    operation_id = "serveShipSchema",
    get,
    path = "/api/v1/ship/schema",
    responses(
        (status = 200, description = "ship.* op catalog (names, args, returns, permissions)"),
    ),
    tag = "framework"
)]
pub async fn serve_schema() -> Json<MeshResponse> {
    Json(MeshResponse {
        ok: true,
        data: serde_json::json!({ "ops": &*OPS }),
    })
}

#[derive(Serialize, Clone, Copy)]
pub struct OpDescriptor {
    pub name: &'static str,
    pub description: &'static str,
    pub args: &'static [ArgDescriptor],
    pub returns: &'static str,
    pub permission: &'static str,
    #[serde(skip_serializing_if = "is_false")]
    pub sensitive: bool,
}

#[derive(Serialize, Clone, Copy)]
pub struct ArgDescriptor {
    pub name: &'static str,
    pub kind: &'static str,
    #[serde(skip_serializing_if = "is_false")]
    pub required: bool,
}

fn is_false(v: &bool) -> bool { !v }

pub(crate) const PROJECT_SCOPE: ArgDescriptor = ArgDescriptor { name: "scope", kind: "string?", required: false };

/// The full registry op catalog, assembled from the per-domain `*_OPS`
/// slices generated by `ship_ops!` (single source — descriptor + dispatch
/// from one declaration) plus `LEGACY_OPS` for domains not yet migrated.
/// Order mirrors the original hand-written catalog so `serve_schema` /
/// `names()` output is unchanged. `OpDescriptor: Copy`, so the assembly is a
/// cheap one-time concat.
///
/// Migrated domains declare their ops via `ship_ops!` (descriptors live with
/// dispatch); unmigrated domains keep entries in `LEGACY_OPS`. Assembly walks
/// `DOMAIN_ORDER` and pulls each domain's slice from whichever source owns it,
/// so the catalog order is identical to the original hand-written array.
pub static OPS: LazyLock<Vec<OpDescriptor>> = LazyLock::new(build_ops);

/// Domain emit order — matches the original `OPS` array exactly.
const DOMAIN_ORDER: &[&str] = &[
    "agents", "skills", "rules", "mcp", "permissions", "pipelines", "events", "specs", "git",
    "settings", "dashboard", "collections", "artifacts", "chat", "sessions", "workspaces",
    "account",
];

fn build_ops() -> Vec<OpDescriptor> {
    use crate::services::registry as reg;
    // Migrated per-domain slices (one declaration per op → descriptor + dispatch).
    let migrated: &[(&str, &[OpDescriptor])] = &[
        ("agents", reg::agents::AGENTS_OPS),
        ("rules", reg::rules::RULES_OPS),
        ("mcp", reg::mcp::MCP_OPS),
        ("permissions", reg::permissions::PERMISSIONS_OPS),
        ("events", reg::events::EVENTS_OPS),
        ("chat", reg::chat::CHAT_OPS),
        ("sessions", reg::sessions::SESSIONS_OPS),
        ("artifacts", reg::artifacts::ARTIFACTS_OPS),
        ("account", reg::account::ACCOUNT_OPS),
        ("skills", reg::skills::SKILLS_OPS),
        ("pipelines", reg::pipelines::PIPELINES_OPS),
        ("specs", reg::specs::SPECS_OPS),
        ("git", reg::git::GIT_OPS),
        ("settings", reg::settings::SETTINGS_OPS),
        ("dashboard", reg::dashboard::DASHBOARD_OPS),
        ("collections", reg::collections::COLLECTIONS_OPS),
        ("workspaces", reg::workspaces::WORKSPACES_OPS),
    ];
    let mut ops: Vec<OpDescriptor> = Vec::new();
    for domain in DOMAIN_ORDER {
        if let Some((_, slice)) = migrated.iter().find(|(d, _)| d == domain) {
            ops.extend_from_slice(slice);
        } else {
            ops.extend(
                LEGACY_OPS
                    .iter()
                    .filter(|o| o.name.split('.').next() == Some(*domain))
                    .copied(),
            );
        }
    }
    ops
}

/// Hand-written descriptors for domains not yet migrated to `ship_ops!`.
/// Shrinks to empty as each domain moves its ops next to its dispatch.
const LEGACY_OPS: &[OpDescriptor] = &[];
