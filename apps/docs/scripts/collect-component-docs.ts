/**
 * collect-component-docs.ts
 *
 * Component reference pages, generated from the packs' CEM output.
 *
 * Source of truth: the per-component custom-elements manifests the
 * sui-compiler mirrors to
 * `.ship/sui-out/packages/components/<family>/<pack>/src/**\/<tag>.custom-elements.json`.
 * We walk the pack SOURCE trees (`packages/components/<family>/<pack>/src`)
 * for component `.sui` files (hyphenated stem — the custom-element tag rule,
 * mirroring deck-bundler's source scan) and pair each with its mirrored CEM,
 * so a deleted component cannot leave a living page and a stale mirror entry
 * never becomes one.
 *
 * Called by collect-skill-docs.ts inside the same delete-then-regen run
 * (pages land under `components/<family>/` in the generated tree), so the
 * drift checker covers these pages automatically. Pages are public-audience
 * (component API reference) and identical in user and internal modes;
 * private packs (`"private": true` in the pack's package.json) are skipped
 * in both.
 *
 * CEM files are build output (`.ship/sui-out` is gitignored). On a checkout
 * that hasn't compiled the packs we skip the affected components and print
 * the bake instruction — same stance as the SUI bundle copy in
 * collect-skill-docs.ts.
 */
import { existsSync, readFileSync, readdirSync, mkdirSync, writeFileSync } from "fs"
import { join, resolve, relative, dirname } from "path"

const SCRIPT_DIR = dirname(new URL(import.meta.url).pathname)
const REPO_ROOT = resolve(SCRIPT_DIR, "../../../")
const PACKS_ROOT = join(REPO_ROOT, "packages/components")
const SUI_OUT = join(REPO_ROOT, ".ship/sui-out")
/** Pack families — one sidebar group (and output subdir) per family. */
const FAMILIES = ["sui", "ship"] as const
const BAKE_HINT =
  "Compile the packs first: 'cargo run -p sui-compiler -- build packages/components'."

interface CemTyped { text?: string }
interface CemAttr { name?: string; description?: string; default?: string; type?: CemTyped }
interface CemMember { kind?: string; attribute?: string; reflects?: boolean }
interface CemNamed { name?: string; description?: string; type?: CemTyped; default?: string }
interface CemDecl {
  tagName?: string
  customElement?: boolean
  description?: string
  attributes?: CemAttr[]
  members?: CemMember[]
  events?: CemNamed[]
  slots?: CemNamed[]
  cssParts?: CemNamed[]
  cssProperties?: CemNamed[]
}

/** Escape `|` so type unions like `'a' | 'b'` survive a markdown table cell. */
function cell(s: string): string {
  return s.replace(/\|/g, "\\|")
}

/** A value rendered as inline code, or an em-dash when absent. */
function codeOrDash(v: string | undefined): string {
  if (v === undefined) return "—"
  return v === "" ? '`""`' : `\`${cell(v)}\``
}

function banner(sourceRel: string, cemRel: string): string {
  return (
    `<!-- AUTO-GENERATED by apps/docs/scripts/collect-component-docs.ts.\n` +
    `     Source: ${sourceRel}\n` +
    `     CEM: ${cemRel}\n` +
    `     Edits to this file are blown away on the next watcher tick. -->\n\n`
  )
}

/** Component `.sui` sources under `dir`: hyphenated stem, never page/index. */
function componentSources(dir: string): string[] {
  const out: string[] = []
  if (!existsSync(dir)) return out
  for (const e of readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = join(dir, e.name)
    if (e.isDirectory()) {
      if (e.name === "node_modules" || e.name === "dist") continue
      out.push(...componentSources(p))
    } else if (e.isFile() && e.name.endsWith(".sui")) {
      const stem = e.name.slice(0, -".sui".length)
      if (stem.includes("-") && stem !== "page" && stem !== "index") out.push(p)
    }
  }
  return out
}

function renderTables(decl: CemDecl): string {
  let body = ""
  // Props — attribute view joined with the member view for `reflects`.
  const reflectsByAttr = new Map<string, boolean>()
  for (const m of decl.members ?? []) {
    if (m.attribute) reflectsByAttr.set(m.attribute, m.reflects === true)
  }
  const attrs = decl.attributes ?? []
  if (attrs.length > 0) {
    // The Description column appears only when at least one prop carries a
    // description — today's CEM emitter (crates/sui/compiler/src/emit/cem.rs)
    // only sets it when authored, and an all-empty column is noise.
    const withDesc = attrs.some((a) => (a.description ?? "") !== "")
    body += withDesc
      ? "## Props\n\n| Name | Type | Default | Reflects | Description |\n|------|------|---------|----------|-------------|\n"
      : "## Props\n\n| Name | Type | Default | Reflects |\n|------|------|---------|----------|\n"
    for (const a of attrs) {
      const reflects = reflectsByAttr.get(a.name ?? "") ? "yes" : "no"
      body += `| \`${cell(a.name ?? "")}\` | ${codeOrDash(a.type?.text)} | ${codeOrDash(a.default)} | ${reflects} |`
      body += withDesc ? ` ${cell(a.description ?? "")} |\n` : "\n"
    }
    body += "\n"
  }
  const events = decl.events ?? []
  if (events.length > 0) {
    body += "## Events\n\n| Event | Detail type | Description |\n|-------|-------------|-------------|\n"
    for (const e of events) {
      body += `| \`${cell(e.name ?? "")}\` | ${codeOrDash(e.type?.text ?? "CustomEvent")} | ${cell(e.description ?? "")} |\n`
    }
    body += "\n"
  }
  const slots = decl.slots ?? []
  if (slots.length > 0) {
    body += "## Slots\n\n| Slot | Description |\n|------|-------------|\n"
    for (const s of slots) {
      body += `| \`${cell(s.name || "(default)")}\` | ${cell(s.description ?? "")} |\n`
    }
    body += "\n"
  }
  const parts = decl.cssParts ?? []
  if (parts.length > 0) {
    body += "## CSS parts\n\n| Part | Description |\n|------|-------------|\n"
    for (const p of parts) {
      body += `| \`::part(${cell(p.name ?? "")})\` | ${cell(p.description ?? "")} |\n`
    }
    body += "\n"
  }
  const cssProps = decl.cssProperties ?? []
  if (cssProps.length > 0) {
    body += "## CSS custom properties\n\n| Name | Default | Description |\n|------|---------|-------------|\n"
    for (const c of cssProps) {
      body += `| \`${cell(c.name ?? "")}\` | ${codeOrDash(c.default)} | ${cell(c.description ?? "")} |\n`
    }
    body += "\n"
  }
  return body
}

function renderPage(decl: CemDecl, packName: string, sourceRel: string, cemRel: string): string {
  const tag = decl.tagName ?? ""
  const description = (decl.description ?? "").trim()
  const summary = description.split("\n")[0] ?? ""
  const fm = ["---", `title: "${tag}"`]
  if (summary) fm.push(`description: "${summary.replace(/"/g, '\\"')}"`)
  fm.push("---", "")
  let body = `\`<${tag}>\` — from pack \`${packName}\` (\`${sourceRel}\`).\n\n`
  if (description) body += `${description}\n\n`
  body += renderTables(decl)
  return fm.join("\n") + banner(sourceRel, cemRel) + body
}

/**
 * Emit one page per public pack component into
 * `<generatedDir>/components/<family>/<tag>.md`. Returns the page count.
 */
export function collectComponentDocs(generatedDir: string): number {
  if (!existsSync(PACKS_ROOT)) {
    console.log("[collect-docs] No packages/components directory, skipping component reference.")
    return 0
  }
  let total = 0
  let missingCems = 0
  for (const family of FAMILIES) {
    const familyDir = join(PACKS_ROOT, family)
    if (!existsSync(familyDir)) continue
    const packs = readdirSync(familyDir, { withFileTypes: true })
      .filter((d) => d.isDirectory())
      .map((d) => d.name)
      .sort()
    for (const pack of packs) {
      const packRoot = join(familyDir, pack)
      const pkgJsonPath = join(packRoot, "package.json")
      if (!existsSync(pkgJsonPath)) continue
      const pkg = JSON.parse(readFileSync(pkgJsonPath, "utf8")) as { name?: string; private?: boolean }
      if (pkg.private === true) continue // public components only
      const packName = pkg.name ?? `${family}/${pack}`

      let count = 0
      for (const src of componentSources(join(packRoot, "src"))) {
        const sourceRel = relative(REPO_ROOT, src)
        const stem = src.slice(src.lastIndexOf("/") + 1, -".sui".length)
        const cemAbs = join(SUI_OUT, dirname(sourceRel), `${stem}.custom-elements.json`)
        if (!existsSync(cemAbs)) {
          missingCems++
          continue
        }
        const cem = JSON.parse(readFileSync(cemAbs, "utf8")) as {
          modules?: Array<{ declarations?: CemDecl[] }>
        }
        const cemRel = relative(REPO_ROOT, cemAbs)
        for (const mod of cem.modules ?? []) {
          for (const decl of mod.declarations ?? []) {
            if (!decl.tagName || decl.customElement !== true) continue
            const outDir = join(generatedDir, "components", family)
            mkdirSync(outDir, { recursive: true })
            writeFileSync(
              join(outDir, `${decl.tagName}.md`),
              renderPage(decl, packName, sourceRel, cemRel),
              "utf8",
            )
            count++
          }
        }
      }
      if (count > 0) console.log(`[collect-docs] packages/components/${family}/${pack} → ${count} page(s)`)
      total += count
    }
  }
  if (missingCems > 0) {
    console.log(`[collect-docs] ${missingCems} component CEM(s) missing under .ship/sui-out — pages skipped. ${BAKE_HINT}`)
  }
  return total
}
