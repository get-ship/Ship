//! MCP tool: generate a starter Ship view template.
//!
//! No filesystem writes — returns the Jinja source and the manifest as
//! strings so the caller's Edit/Write tool owns the commit. Keeps template
//! idioms consistent across agent authors.

use crate::requests::ViewScaffoldRequest;

/// Dispatch by shape, return a JSON payload carrying the template string,
/// the manifest string, and suggested write paths.
pub fn view_scaffold(req: ViewScaffoldRequest) -> String {
    let name = req.name.trim();
    if name.is_empty() {
        return "Error: `name` is required".to_string();
    }
    let shape = req
        .shape
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .unwrap_or("blank");
    let collection = req.collection.as_deref().unwrap_or("<collection>");

    let needs_collection = matches!(shape, "list" | "list-edit-delete" | "form" | "detail");
    if needs_collection && req.collection.as_deref().map(str::is_empty).unwrap_or(true) {
        return format!(
            "Error: shape `{shape}` requires a `collection` argument"
        );
    }

    let template = match shape {
        "blank" => template_blank(name),
        "list" => template_list(name, collection),
        "list-edit-delete" => template_list_edit_delete(name, collection),
        "form" => template_form(name, collection),
        "detail" => template_detail(name, collection),
        "tabs" => template_tabs(name),
        other => {
            return format!(
                "Error: unknown shape `{other}`; expected one of blank, list, list-edit-delete, form, detail, tabs"
            );
        }
    };

    let manifest = manifest_for(name, shape, collection);

    let payload = serde_json::json!({
        "template": template,
        "manifest": manifest,
        "suggested_path": format!(".ship/views/{name}/index.html.j2"),
        "suggested_manifest_path": format!(".ship/views/{name}/manifest.jsonc"),
    });
    serde_json::to_string_pretty(&payload).unwrap_or_else(|_| "{}".to_string())
}

fn header() -> &'static str {
    "{#- Generated by ship_view_scaffold — replace this header with the view's real description -#}"
}

fn imports() -> &'static str {
    r#"{% from "_ship.html.j2" import ship_view_chrome, signal, form, delete %}"#
}

fn manifest_for(name: &str, shape: &str, collection: &str) -> String {
    let desc = format!("Scaffolded {shape} view for `{collection}` — replace this summary.");
    format!(
        "{{\n  \"name\": \"{name}\",\n  \"type\": \"html\",\n  \"description\": \"{desc}\",\n  \"packs\": []\n}}\n"
    )
}

fn template_blank(name: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  <ship-empty-state
    icon=\"sparkles\"
    headline=\"Nothing here yet\"
    description=\"Scaffolded blank view — replace this block with your real content.\">
  </ship-empty-state>
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

fn template_list(name: &str, collection: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  {{{{ signal('query', '') }}}}

  <ship-toolbar>
    <ship-text-field placeholder=\"Search {collection}…\" data-bind=\"query\"></ship-text-field>
  </ship-toolbar>

  {{% live collection='{collection}' as='items' where={{'name': {{'$contains': '$query'}}}} %}}
    {{% if items %}}
      <ship-list>
        {{% for item in items %}}
          <ship-list-tile
            headline=\"{{{{ item.name }}}}\"
            supporting=\"{{{{ item.updated_at }}}}\"
            href=\"/views/{name}/{{{{ item.id }}}}\">
          </ship-list-tile>
        {{% endfor %}}
      </ship-list>
    {{% else %}}
      <ship-empty-state headline=\"No {collection} yet\"></ship-empty-state>
    {{% endif %}}
  {{% endlive %}}
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

fn template_list_edit_delete(name: &str, collection: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  <ship-card>
    <h3 slot=\"header\">Add {collection}</h3>
    {{{{ form('{collection}', fields=['name'], submit_label='Add') }}}}
  </ship-card>

  {{% live collection='{collection}' as='items' %}}
    {{% if items %}}
      <ship-list>
        {{% for item in items %}}
          <ship-list-tile
            headline=\"{{{{ item.name }}}}\"
            supporting=\"{{{{ item.updated_at }}}}\">
            <div slot=\"trailing\">
              {{{{ delete('{collection}', item.id, confirm=true) }}}}
            </div>
          </ship-list-tile>
        {{% endfor %}}
      </ship-list>
    {{% else %}}
      <ship-empty-state headline=\"No {collection} yet\"></ship-empty-state>
    {{% endif %}}
  {{% endlive %}}
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

fn template_form(name: &str, collection: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  <ship-card>
    <h2 slot=\"header\">{name}</h2>
    {{{{ form('{collection}',
             fields=['name', 'description'],
             submit_label='Save',
             on_success='/views/{name}') }}}}
  </ship-card>
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

fn template_detail(name: &str, collection: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  {{{{ signal('selected', none) }}}}

  <div class=\"split\">
    <aside class=\"pane pane--list\">
      {{% live collection='{collection}' as='items' %}}
        <ship-list>
          {{% for item in items %}}
            <ship-list-tile
              headline=\"{{{{ item.name }}}}\"
              data-on-click=\"$selected = '{{{{ item.id }}}}'\"
              data-selected=\"$selected === '{{{{ item.id }}}}'\">
            </ship-list-tile>
          {{% endfor %}}
        </ship-list>
      {{% endlive %}}
    </aside>

    <section class=\"pane pane--detail\" data-show=\"$selected\">
      {{% live collection='{collection}' id='$selected' as='item' %}}
        {{% if item %}}
          <ship-card>
            <h2 slot=\"header\">{{{{ item.name }}}}</h2>
            <p>{{{{ item.description }}}}</p>
          </ship-card>
        {{% else %}}
          <ship-empty-state headline=\"Select an item\"></ship-empty-state>
        {{% endif %}}
      {{% endlive %}}
    </section>
  </div>

  <style>
    .split {{ display: grid; grid-template-columns: 320px 1fr; gap: var(--ship-space-4); }}
    .pane {{ min-width: 0; }}
  </style>
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

fn template_tabs(name: &str) -> String {
    format!(
        "{h}
{imp}

{{% call ship_view_chrome(title='{name}') %}}
  <ship-tabs>
    <ship-tab slot=\"tab\" value=\"overview\">Overview</ship-tab>
    <ship-tab slot=\"tab\" value=\"activity\">Activity</ship-tab>
    <ship-tab slot=\"tab\" value=\"settings\">Settings</ship-tab>

    <section slot=\"panel\" data-tab=\"overview\">
      <ship-empty-state headline=\"Overview\"></ship-empty-state>
    </section>
    <section slot=\"panel\" data-tab=\"activity\">
      <ship-empty-state headline=\"Activity\"></ship-empty-state>
    </section>
    <section slot=\"panel\" data-tab=\"settings\">
      <ship-empty-state headline=\"Settings\"></ship-empty-state>
    </section>
  </ship-tabs>
{{% endcall %}}
",
        h = header(),
        imp = imports(),
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    fn req(name: &str, shape: &str, collection: Option<&str>) -> ViewScaffoldRequest {
        ViewScaffoldRequest {
            name: name.to_string(),
            collection: collection.map(|s| s.to_string()),
            shape: Some(shape.to_string()),
        }
    }

    #[test]
    fn blank_shape_returns_template_and_manifest() {
        let out = view_scaffold(req("notes", "blank", None));
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        let t = v["template"].as_str().unwrap();
        assert!(t.contains("Generated by ship_view_scaffold"));
        assert!(t.contains("ship_view_chrome"));
        assert!(t.contains("ship-empty-state"));
        assert_eq!(v["suggested_path"], ".ship/views/notes/index.html.j2");
    }

    #[test]
    fn list_edit_delete_requires_collection() {
        let out = view_scaffold(req("tasks", "list-edit-delete", None));
        assert!(out.starts_with("Error:"), "expected error, got: {out}");
    }

    #[test]
    fn list_edit_delete_emits_form_and_delete() {
        let out = view_scaffold(req("tasks", "list-edit-delete", Some("tasks")));
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        let t = v["template"].as_str().unwrap();
        assert!(t.contains("form('tasks'"));
        assert!(t.contains("delete('tasks'"));
        assert!(t.contains("ship-list-tile"));
    }

    #[test]
    fn unknown_shape_errors() {
        let out = view_scaffold(req("x", "wizard", Some("c")));
        assert!(out.contains("unknown shape"), "got: {out}");
    }

    #[test]
    fn empty_name_errors() {
        let out = view_scaffold(req("", "blank", None));
        assert!(out.starts_with("Error:"));
    }

    #[test]
    fn tabs_does_not_require_collection() {
        let out = view_scaffold(req("settings", "tabs", None));
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        assert!(v["template"].as_str().unwrap().contains("ship-tabs"));
    }

    #[test]
    fn manifest_includes_name_and_type() {
        let out = view_scaffold(req("notes", "blank", None));
        let v: serde_json::Value = serde_json::from_str(&out).unwrap();
        let m = v["manifest"].as_str().unwrap();
        assert!(m.contains("\"name\": \"notes\""));
        assert!(m.contains("\"type\": \"html\""));
        assert!(m.contains("\"packs\": []"));
    }
}
