#!/usr/bin/env bun
// Generate the typed dynamic-route table from the view file tree (SSOT).
//
// Walks the shell's studio view dirs for any route segment of the form
// `[param]`, reconstructs its pattern (`[id]` → `:id`), and emits
// `apps/shell/src/studio/routes.gen.ts`:
//   - STUDIO_ROUTE_PATTERNS — the RouteShape[] the shell registers once via
//     defineRoutes (so route.params.<name> resolves).
//   - studioRoutes — typed path builders, e.g. studioRoutes.agentsId({ id }).
//
// This is the codegen half of ADR `unified-deck-router`: typed routes from
// the file tree we already discover (TanStack DX, no inference, no runtime).
// Run: `bun scripts/gen-routes.ts` (or via `just gen-routes`).
//
// NOTE (#168): this discovery duplicates the view-tree walk the daemon's
// bundler already does; the plan is to fold route emission into deck/daemon
// route discovery so it generalizes beyond the shell's studio.

import { existsSync, readdirSync, writeFileSync } from 'node:fs'
import { join, relative } from 'node:path'
import { fileURLToPath } from 'node:url'

interface Route {
  pattern: string
  params: string[]
  builder: string
}

const repoRoot = join(fileURLToPath(import.meta.url), '..', '..')
const STUDIO_DIR = join(repoRoot, 'apps/shell/src/studio')
const OUT = join(STUDIO_DIR, 'routes.gen.ts')

/** Recursively collect dirs that hold a mountable view (`page.sui`). */
function viewDirs(dir: string, acc: string[] = []): string[] {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    if (!e.isDirectory()) continue
    const child = join(dir, e.name)
    if (existsSync(join(child, 'page.sui'))) acc.push(child)
    viewDirs(child, acc)
  }
  return acc
}

/** `agents/[id]/settings` → { pattern: '/studio/agents/:id/settings',
 *   params: ['id'], builder: 'agentsIdSettings' }. Dynamic routes only. */
function toRoute(dir: string): Route | null {
  const rel = relative(STUDIO_DIR, dir).split(/[/\\]/)
  const params: string[] = []
  const segs = rel.map((s) => {
    const m = /^\[(.+)\]$/.exec(s)
    if (m) {
      params.push(m[1])
      return ':' + m[1]
    }
    return s
  })
  if (params.length === 0) return null // static route — no defineRoutes needed
  const pattern = '/studio/' + segs.join('/')
  // Builder name: camelCase of the segments (params kept by name).
  const builder = rel
    .map((s) => s.replace(/^\[(.+)\]$/, '$1'))
    .join('-')
    .replace(/-([a-z])/g, (_, c: string) => c.toUpperCase())
  return { pattern, params, builder }
}

const routes = viewDirs(STUDIO_DIR)
  .map(toRoute)
  .filter((r): r is Route => r !== null)
  .sort((a, b) => a.pattern.localeCompare(b.pattern))

const patternLines = routes.map((r) => `  { pattern: '${r.pattern}' },`).join('\n')

const builderLines = routes
  .map((r) => {
    const arg = `p: { ${r.params.map((k) => `${k}: string`).join('; ')} }`
    const path = '`' + r.pattern.replace(/:([a-zA-Z0-9_]+)/g, '${p.$1}') + '`'
    return `  /** ${r.pattern} */\n  ${r.builder}: (${arg}): string => ${path},`
  })
  .join('\n')

const body = `// @generated by scripts/gen-routes.ts — DO NOT EDIT.
// Typed dynamic-route table for the studio view tree. Regenerate with
// \`bun scripts/gen-routes.ts\` (or \`just gen-routes\`) after adding or
// renaming a \`[param]\` route dir. See ADR unified-deck-router.

import type { RouteShape } from '@ship/sui-runtime'

/** Every dynamic studio route pattern. The shell registers these once via
 *  defineRoutes so route.params.<name> resolves. */
export const STUDIO_ROUTE_PATTERNS: RouteShape[] = [
${patternLines}
]

/** Typed path builders — \`navigate(studioRoutes.agentsId({ id }))\`. The
 *  param keys are checked at compile time; you cannot typo or omit one. */
export const studioRoutes = {
${builderLines}
}
`

writeFileSync(OUT, body)
console.log(`✓ routes.gen.ts (${routes.length} dynamic routes)`)
